package org.jetbrains.kotlin.wasm.test.tools

import java.io.File

/**
 * Turns a WASI core module produced by a test into a WASI 0.2 component, which is the only form a host can run:
 * the standard library imports `wasi:*` 0.2 interfaces directly.
 *
 * The WIT is embedded in two steps, since `wasm-tools component new` unions all embedded worlds:
 *  1. the standard library's `wasip2-imports` world, describing what the standard library imports,
 *  2. an export-only world for the entry point the test is going to invoke, which is why [ENTRY_POINTS_WIT] needs
 *     nothing from the standard library's WIT package.
 *
 * Configuration (all optional):
 *  - `wasm.tools.path` - `wasm-tools` executable, provisioned by the `wasm-tools-configuration` plugin,
 *  - `kotlin.wasm.wit.dir` - the standard library's WIT directory, by default found relative to the repository root.
 */
internal object WasiComponentizer {
    /** Entry point of the box test runner, see `wasiBoxTestRun.kt`. */
    const val BOX_ENTRY_POINT: String = "start-test"

    /** Entry point of the unit test runner, generated by the Wasm backend (`wasmWasiUnitTestsExportName`). */
    const val UNIT_TESTS_ENTRY_POINT: String = "start-unit-tests"

    private const val STDLIB_IMPORTS_WORLD = "kotlin-stdlib:wasip2/wasip2-imports"
    private const val ENTRY_POINTS_PACKAGE = "kotlin-test:wasi-entry-points"

    /** One export-only world per entry point; a world name is the name of the entry point it exports. */
    private val ENTRY_POINTS_WIT: String =
        listOf(BOX_ENTRY_POINT, UNIT_TESTS_ENTRY_POINT).joinToString(
            separator = "\n\n",
            prefix = "package $ENTRY_POINTS_PACKAGE@1.0.0;\n\n"
        ) { entryPoint ->
            """
            world $entryPoint {
                export $entryPoint: func();
            }
            """.trimIndent()
        }

    private val wasmTools: String = System.getProperty("wasm.tools.path") ?: "wasm-tools"

    private val stdlibWitDir: File by lazy {
        val dir = System.getProperty("kotlin.wasm.wit.dir")?.let(::File) ?: findStdlibWitDir()
        check(dir.isDirectory) { "stdlib WIT directory not found at ${dir.absolutePath}" }
        dir
    }

    private val entryPointsWit: File by lazy {
        File.createTempFile("wasi-entry-points-", ".wit")
            .also { it.deleteOnExit() }
            .apply { writeText(ENTRY_POINTS_WIT) }
    }

    private fun findStdlibWitDir(): File {
        val relative = "libraries/stdlib/wasm/wasi/internal/wit"
        var candidate: File? = File("").absoluteFile
        while (candidate != null) {
            val wit = File(candidate, relative)
            if (wit.isDirectory) return wit
            candidate = candidate.parentFile
        }
        error("Could not find '$relative' in any parent of ${File("").absolutePath}; set -Dkotlin.wasm.wit.dir=...")
    }

    /**
     * Builds a component out of [coreModule], exporting [entryPoint], and returns it. Intermediate files and the
     * component are written next to the original module.
     */
    fun componentize(coreModule: File, entryPoint: String): File {
        check(coreModule.isFile) { "${coreModule.absolutePath} does not exist" }

        fun sibling(suffix: String) = File(coreModule.parentFile, "${coreModule.nameWithoutExtension}.$suffix.wasm")

        val withImports = sibling("imports-embedded")
        val withEntryPoint = sibling("entry-point-embedded")
        val component = sibling("component")

        embed(stdlibWitDir, STDLIB_IMPORTS_WORLD, coreModule, withImports)
        embed(entryPointsWit, "$ENTRY_POINTS_PACKAGE/$entryPoint", withImports, withEntryPoint)
        runWasmTools("component", "new", withEntryPoint.absolutePath, "-o", component.absolutePath)

        return component
    }

    private fun embed(wit: File, world: String, module: File, output: File) {
        runWasmTools(
            "component", "embed", wit.absolutePath, module.absolutePath, "--world", world, "-o", output.absolutePath
        )
    }

    private fun runWasmTools(vararg arguments: String) {
        val command = listOf(wasmTools) + arguments
        val process = ProcessBuilder(command).redirectErrorStream(true).start()
        val output = process.inputStream.bufferedReader().readText()
        val exitCode = process.waitFor()
        check(exitCode == 0) {
            "Command \"${command.joinToString(" ") { escapeShellArgument(it) }}\" " +
                    "terminated with exit code $exitCode\nOUTPUT:\n$output\n---"
        }
    }
}
