import org.jetbrains.kotlin.js.config.useEs6DefaultArgs

/**
 * Optimizes default argument initialization statements generated by [JsDefaultArgumentStubGenerator] by moving the default argument
 * expressions back to [IrValueParameter.defaultValue] whenever possible, which will force the codegen to emit the
 * [ES2015 default parameter syntax](https://developer.mozilla.org/en-US/docs/Web/JavaScript/Reference/Functions/Default_parameters).
 *
 * The conditions when it's possible to perform this optimization are:
 * - There are no statements prior to the default argument initialization statements
 * - The order of initialization statements matches the order of the corresponding parameters
 * - The structure of these statements matches whatever [JsDefaultArgumentStubGenerator] generates.
 *
 * You may ask: why is this a separate pass, why can't we just drop [JsDefaultArgumentStubGenerator] altogether and keep
 * [IrValueParameter.defaultValue] as is? The answer is that there are still some cases where we have to generate initialization statements,
 * like when this is a top-level function in a file with lazily initialized properties — those properties must be initialized _before_
 * any of the default arguments are evaluated.
 *
 * And if during whole-world optimization we determine that all lazily initialized properties in a file can be eagerly initialized,
 * and the call to the file initializer is eliminated, we can apply this optimization after that (but not before).
 */
class JsDefaultArgumentOptimizationLowering(private val context: JsIrOptimizationContext) : ChangeAwareBodyLoweringPass() {
    override fun lower(irBody: IrBody, container: IrDeclaration) {
        if (!context.configuration.useEs6DefaultArgs) return
        if (container !is IrFunction || irBody !is IrBlockBody) return
        var lastTransformedParameterIndex = -1
        val oldStatements = irBody.statements.toList()
        irBody.statements.clear()

        var numberOfRemovedStatements = 0
        for (statement in oldStatements) {
            // We expect a default argument stub to have the following form:
            // SET_VAR '<function parameter>'
            //   WHEN
            //     BRANCH
            //       if: CALL 'internal final fun jsEqeqeq (a: kotlin.Any?, b: kotlin.Any?): kotlin.Boolean declared in kotlin'
            //         ARG a: GET_VAR '<function parameter>'
            //         ARG b: GET_FIELD 'FIELD PROPERTY_BACKING_FIELD name:VOID type:kotlin.Nothing? visibility:private [final,static]'
            //       then: <default value>
            //     BRANCH
            //       if: CONST Boolean type=kotlin.Boolean value=true
            //       then: GET_VAR '<function parameter>'
            if (statement !is IrSetValue) break
            val parameter = statement.symbol.owner as? IrValueParameter ?: break
            if (parameter.indexInParameters <= lastTransformedParameterIndex) {
                // Default parameters must be initialized in the same order as they are declared.
                break
            }

            val assignedValue = statement.value
            if (assignedValue !is IrWhen || assignedValue.branches.size != 2) break
            val elseBranch = assignedValue.branches[1]
            if (!isElseBranch(elseBranch)) return
            val condition = assignedValue.branches[0].condition
            if (condition !is IrCall || condition.symbol != context.symbols.jsEqeqeq || condition.arguments.size != 2) break
            if ((condition.arguments[0] as? IrGetValue)?.symbol != parameter.symbol) break
            if ((condition.arguments[1] as? IrGetField)?.symbol?.owner?.correspondingPropertySymbol != context.symbols.void) break
            if ((elseBranch.result as? IrGetValue)?.symbol != parameter.symbol) break
            parameter.defaultValue = context.irFactory.createExpressionBody(assignedValue.branches[0].result)
            numberOfRemovedStatements += 1
            lastTransformedParameterIndex = parameter.indexInParameters
            hasChanges = true
        }

        irBody.statements.addAll(oldStatements.subList(numberOfRemovedStatements, oldStatements.size))
    }
}
