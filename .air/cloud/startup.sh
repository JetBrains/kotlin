#!/usr/bin/env bash
# Air cloud environment startup script for the Kotlin repository.
#
# - Installs the JDKs the build expects (Temurin 8/11/17/21/25) into ~/.jdks and exposes them
#   through the JDK_* variables listed in gradle.properties (org.gradle.java.installations.fromEnv).
#   Other toolchains (e.g. JDK 9) are still auto-provisioned by Gradle via foojay.
# - Points Gradle (wrapper, daemon) at the egress proxy: the JVM does not read HTTPS_PROXY itself.
# - WARMUP mode: downloads Gradle, resolves dependencies and compiles the compiler so the snapshot
#   carries warm Gradle caches; the healthcheck asserts that the build actually works.
set -euo pipefail

if [ "${AIR_STARTUP_MODE:-}" = warmup ]; then WARMUP=1; else WARMUP=; fi

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
JDKS_DIR="$HOME/.jdks"
ENV_FILE="$HOME/.air-kotlin-env.sh"
JDK_VERSIONS="8 11 17 21 25"

log() { echo "[startup $(date +%H:%M:%S)] $*"; }

# Maps a major Java version to the env variable name used by the build (see JvmToolchain.kt).
jdk_env_name() {
  case "$1" in
    8) echo JDK_1_8 ;;
    *) echo "JDK_${1}_0" ;;
  esac
}

install_jdk() {
  local version="$1" dest="$JDKS_DIR/temurin-$1"
  if [ -x "$dest/bin/javac" ]; then
    log "JDK $version already installed at $dest"
    return
  fi
  log "Installing Temurin JDK $version ..."
  local tmp
  tmp="$(mktemp -d)"
  curl -fsSL --retry 5 --retry-delay 5 -o "$tmp/jdk.tar.gz" \
    "https://api.adoptium.net/v3/binary/latest/${version}/ga/linux/x64/jdk/hotspot/normal/eclipse"
  mkdir -p "$tmp/x"
  tar -xzf "$tmp/jdk.tar.gz" -C "$tmp/x"
  rm -rf "$dest"
  mkdir -p "$JDKS_DIR"
  mv "$tmp/x"/* "$dest"
  rm -rf "$tmp"
  log "JDK $version installed: $("$dest/bin/java" -version 2>&1 | head -1)"
}

configure_gradle_proxy() {
  local proxy="${HTTPS_PROXY:-${https_proxy:-}}"
  local props="$HOME/.gradle/gradle.properties"
  mkdir -p "$HOME/.gradle"
  touch "$props"
  # Drop previously generated proxy lines, keep anything else the user put there.
  sed -i '/^systemProp\.https\?\.\(proxyHost\|proxyPort\|nonProxyHosts\)=/d' "$props"
  if [ -z "$proxy" ]; then
    log "No HTTPS_PROXY set; Gradle will connect directly"
    return
  fi
  local hostport="${proxy#*://}"
  hostport="${hostport#*@}"
  hostport="${hostport%%/*}"
  local host="${hostport%:*}" port="${hostport##*:}"
  [ "$port" = "$hostport" ] && port=80
  cat >> "$props" <<EOF
systemProp.http.proxyHost=$host
systemProp.http.proxyPort=$port
systemProp.https.proxyHost=$host
systemProp.https.proxyPort=$port
systemProp.http.nonProxyHosts=localhost|127.0.0.1
EOF
  log "Configured Gradle proxy $host:$port in $props"
}

# The internal-gradle-setup settings plugin otherwise blocks the build on an interactive consent
# prompt for automatic local.properties configuration. Decline it unless the user already decided.
configure_gradle_consent() {
  local props="$HOME/.gradle/gradle.properties"
  if ! grep -q '^kotlin\.build\.internal\.gradle\.setup\.consent=' "$props"; then
    echo "kotlin.build.internal.gradle.setup.consent=false" >> "$props"
    log "Declined automatic local.properties setup in $props (set the property to true to opt in)"
  fi
}

write_env_file() {
  {
    echo "# Generated by .air/cloud/startup.sh"
    for v in $JDK_VERSIONS; do
      echo "export $(jdk_env_name "$v")=\"$JDKS_DIR/temurin-$v\""
    done
  } > "$ENV_FILE"

  local line="[ -f \"$ENV_FILE\" ] && . \"$ENV_FILE\" # air-kotlin-env"
  local profile=""
  for f in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
    if [ -f "$f" ]; then profile="$f"; break; fi
  done
  [ -n "$profile" ] || profile="$HOME/.profile"
  for f in "$profile" "$HOME/.bashrc"; do
    touch "$f"
    grep -q '# air-kotlin-env' "$f" || echo "$line" >> "$f"
  done
  log "Wrote $ENV_FILE (sourced from $profile and ~/.bashrc)"
}

healthcheck() {
  cd "$REPO_DIR"
  log "Healthcheck: compiling the Kotlin compiler (:compiler:cli:classes) ..."
  # Gradle owns its own network retries; the outer setup applies the overall timeout.
  ( while sleep 60; do log "Healthcheck: build still running ..."; done ) &
  local ticker=$!
  local rc=0
  ./gradlew :compiler:cli:classes --console=plain -q </dev/null || rc=$?
  kill "$ticker" 2>/dev/null || true
  if [ "$rc" -ne 0 ]; then
    log "Healthcheck FAILED: ./gradlew :compiler:cli:classes exited with $rc"
    return "$rc"
  fi
  log "Healthcheck passed"
}

main() {
  cd "$REPO_DIR"
  chmod +x gradlew

  for v in $JDK_VERSIONS; do install_jdk "$v"; done
  write_env_file
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  configure_gradle_proxy
  configure_gradle_consent

  if [ -n "$WARMUP" ]; then
    healthcheck
    log "Stopping Gradle daemons so the snapshot is taken from a quiet filesystem"
    ./gradlew --stop --console=plain </dev/null || true
  fi
  log "Startup finished"
}

main "$@"
