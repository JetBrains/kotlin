/**
 * Light classes for declarations generated by a resolve extension.
 *
 * The expected output records the current behavior: the symbol-based conversion works,
 * but [JavaPsiFacade] finds neither the class nor the facade, and the package lists no classes (KT-59330).
 */
class SymbolLightClassesResolveExtensionTest : AbstractAnalysisApiExecutionTest(testDirPathString = "testData/resolveExtension") {
    override val configurator = LLSourceLikeTestConfigurator()

    override fun configureTest(builder: TestConfigurationBuilder) {
        super.configureTest(builder)
        KtResolveExtensionTestSupport.configure(builder)
    }

    @Test
    fun resolveExtensionLightClasses(file: KtFile, testServices: TestServices) {
        val project = file.project
        val scope = GlobalSearchScope.allScope(project)
        val facade = JavaPsiFacade.getInstance(project)

        val bySymbol = analyze(file) {
            findClass(ClassId(FqName("rex"), Name.identifier("RexClass")))?.asPsiClass()
        }

        val byFqName = facade.findClass("rex.RexClass", scope)
        val facadeByFqName = facade.findClass("rex.GeneratedKt", scope)
        val classNamesInPackage = facade.findPackage("rex")?.getClasses(scope)?.map { it.name }.orEmpty()

        val actual = buildString {
            appendLine("bySymbol=${bySymbol?.qualifiedName}")
            appendLine("byFqName=${byFqName?.qualifiedName}")
            appendLine("facadeByFqName=${facadeByFqName?.qualifiedName}")
            appendLine("classesInPackage=$classNamesInPackage")
        }

        val expected = """
            bySymbol=rex.RexClass
            byFqName=null
            facadeByFqName=null
            classesInPackage=[]
        """.trimIndent() + "\n"

        testServices.assertions.assertEquals(expected, actual)
    }
}
