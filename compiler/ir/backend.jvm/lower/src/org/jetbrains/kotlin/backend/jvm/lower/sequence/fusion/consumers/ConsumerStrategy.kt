internal fun isConsumerFqName(fqName: String): Boolean = fqName in consumerFqNames

/**
 * Each strategy consists of:
 * 1. getInitialDeclarations - the variables declared before the iteration and used in the consumer body
 * 2. getConsumerBuilder - creates the consumer body for the element given by the producer/transformer,
 *    or returns null if the call can not be fused
 * 3. createResult - the value of the whole fused expression, evaluated after the iteration
 *
 * IR generated by getConsumerBuilder returns a Boolean to the producer/transformer.
 * If the Boolean is `false`, the producer/transformer stops iterating over the sequence after this element,
 * e.g. `first` returns `false` once it has found its element. This is the only way for a consumer to stop the iteration.
 *
 * The variables of a strategy are created in its constructor, so the methods have no side effects and can be called in any order.
 */
internal abstract class ConsumerStrategy(val data: ConsumerData, val expression: IrExpression) {
    abstract fun getInitialDeclarations(): List<IrVariable>

    abstract fun getConsumerBuilder(): ConsumerBodyBuilder?

    abstract fun createResult(): IrExpression
}

// no consumer can tell before the iteration that it needs no elements, so a consumer never skips the iteration
internal fun ConsumerStrategy.createSequenceReplacement(): SequenceReplacement? =
    getConsumerBuilder()?.let { SequenceReplacement(getInitialDeclarations(), skipIteration = null, it, createResult()) }

internal data class ConsumerData(
    val context: JvmBackendContext,
    val builder: IrBuilderWithScope,
    val parent: IrDeclarationParent,
    val sequenceData: SequenceData,
)

internal sealed class CollectionVersion {
    object List : CollectionVersion()
    object Set : CollectionVersion()
    object Collection : CollectionVersion()
}

internal fun createConsumerStrategy(
    expression: IrCall,
    functionFQName: String,
    data: ConsumerData,
    context: JvmBackendContext,
): ConsumerStrategy? {
    return when (functionFQName) {
        // find is equivalent to firstOrNull with a predicate argument
        FIND -> FirstLastStrategy(data, expression, isOrNull = true, isFirst = true, isFind = true)
        FIND_LAST -> FirstLastStrategy(data, expression, isOrNull = true, isFirst = false, isFind = true)
        FIRST -> FirstLastStrategy(data, expression, isOrNull = false, isFirst = true, isFind = false)
        FIRST_OR_NULL -> FirstLastStrategy(data, expression, isOrNull = true, isFirst = true, isFind = false)
        FIRST_NOT_NULL_OF -> FirstNotNullOfStrategy(data, expression, isOrNull = false)
        FIRST_NOT_NULL_OF_OR_NULL -> FirstNotNullOfStrategy(data, expression, isOrNull = true)
        LAST -> FirstLastStrategy(data, expression, isOrNull = false, isFirst = false, isFind = false)
        LAST_OR_NULL -> FirstLastStrategy(data, expression, isOrNull = true, isFirst = false, isFind = false)
        FILTER_TO -> FilterToStrategy(data, expression, FilterVersion.Filter)
        FILTER_NOT_TO -> FilterToStrategy(data, expression, FilterVersion.FilterNot)
        FILTER_NOT_NULL_TO -> FilterToStrategy(data, expression, FilterVersion.FilterNotNull)
        TO_LIST -> ToCollectionStrategy(data, expression, CollectionVersion.List, isReadOnly = true)
        TO_MUTABLE_LIST -> ToCollectionStrategy(data, expression, CollectionVersion.List, isReadOnly = false)
        TO_SET -> ToCollectionStrategy(data, expression, CollectionVersion.Set, isReadOnly = true)
        TO_MUTABLE_SET -> ToCollectionStrategy(data, expression, CollectionVersion.Set, isReadOnly = false)
        TO_COLLECTION -> ToCollectionStrategy(data, expression, CollectionVersion.Collection, isReadOnly = false)
        INDEX_OF -> IndexOfStrategy(data, expression, IndexOfVersion.IndexOf, context)
        INDEX_OF_FIRST -> IndexOfStrategy(data, expression, IndexOfVersion.IndexOfFirst, context)
        INDEX_OF_LAST -> IndexOfStrategy(data, expression, IndexOfVersion.IndexOfLast, context)
        FOR_EACH -> ForEachStrategy(data, expression, false, context)
        FOR_EACH_INDEXED -> ForEachStrategy(data, expression, true, context)
        else -> null
    }
}

internal fun createConsumerStrategy(
    expression: IrBlock,
    data: ConsumerData,
): ConsumerStrategy? {
    val loopData = gatherLoopData(expression, data.parent) ?: return null
    return ForLoopStrategy(data, loopData, expression)
}

fun IrElement.rebindJumps(
    targetLoop: IrLoop,
    onBreak: (IrBreak) -> IrExpression,
    onContinue: (IrContinue) -> IrExpression
) = transformChildrenVoid(object : IrElementTransformerVoid() {
    override fun visitBreak(jump: IrBreak): IrExpression {
        if (jump.loop == targetLoop) return onBreak(jump)
        return super.visitBreak(jump)
    }

    override fun visitContinue(jump: IrContinue): IrExpression {
        if (jump.loop == targetLoop) return onContinue(jump)
        return super.visitContinue(jump)
    }
})
