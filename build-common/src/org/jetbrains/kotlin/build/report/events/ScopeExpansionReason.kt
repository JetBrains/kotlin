package org.jetbrains.kotlin.build.report.events

enum class ScopeExpansionReason(val readableString: String) {
    // Initial dirty set: manual changes
    SOURCE_FILE_CHANGED("Manually edited or added"),
    SOURCE_FILE_REMOVED("Manually removed"),
    PENDING_FROM_PREVIOUS_BUILD("Left over from previous build"),

    // Initial dirty set: dependency changes
    DEPENDENCY_DECLARATION_USED("Uses a changed class"),
    DEPENDENCY_SUPERTYPE_CHANGED("Extends or implements a changed class"),
    JAVA_DECLARATION_USED("Uses a changed Java declaration"),
    ANDROID_LAYOUT_USED("Uses a changed Android layout"),
    REMOVED_CLASS_USED("Uses a removed class"),
    REMOVED_CLASS_SUPERTYPE("Extends or implements a removed class"),

    // Top of every compilation round / iteration
    EXPECT_ACTUAL_COUNTERPART("Contains a part of an expected-actual statement"),
    REFERENCED_BY_COMPILER_PLUGIN("Referenced by a compiler plugin"),
    GENERATED_BY_COMPILER_PLUGIN("Generated by a compiler plugin"),

    ABI_MEMBERS_CHANGED("Members changed: "),
    ABI_REMOVED("Removed: "),
    ABI_SIGNATURE_CHANGED("Signature changed: "),
    ABI_PARENTS_CHANGED("Parents changed: "),

    CLASS_NAME_CLASH("Shares class name with a recompiled file via class/typealias or @JvmMultifileClass declaration"),
//    MULTIFILE_CLASS("Shares a @JvmMultifileClass facade with a recompiled file"),

    FOR_CONSISTENCY("Recompiled for logical consistency"),

    UNKNOWN("Unknown recompilation reason"),
    ;

    override fun toString(): String = readableString
}
