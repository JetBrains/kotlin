package org.jetbrains.kotlin.lombok.checkers

import org.jetbrains.kotlin.diagnostics.DiagnosticReporter
import org.jetbrains.kotlin.diagnostics.reportOn
import org.jetbrains.kotlin.fir.analysis.checkers.context.CheckerContext
import org.jetbrains.kotlin.fir.analysis.checkers.declaration.FirRegularClassChecker
import org.jetbrains.kotlin.fir.declarations.FirRegularClass
import org.jetbrains.kotlin.fir.extensions.declarationGenerators
import org.jetbrains.kotlin.fir.extensions.extensionService
import org.jetbrains.kotlin.lombok.LombokFirDiagnostics
import org.jetbrains.kotlin.lombok.generators.LombokCompanionObjectContributor
import org.jetbrains.kotlin.lombok.generators.LombokCompanionObjectGenerator.Companion.hasSerializableCompanion

/**
 * KT-90321 workaround:
 * Reports a `companion object` generated by `@Serializable` or `@MetaSerializable` since it prevents Lombok's generation.
 *
 * The report goes on the companion object itself, which ultimately reports on the outer class
 */
object FirLombokSerializableCompanionObjectChecker : FirRegularClassChecker(Platform) {
    context(context: CheckerContext, reporter: DiagnosticReporter)
    override fun check(declaration: FirRegularClass) {
        val companion = declaration.companionObjectSymbol ?: return

        // A source-defined companion object is fine
        if (!companion.origin.generated) return

        // The generators decide what needs a companion object; asking them keeps this from re-deriving which
        // annotation on which declaration generates a static member.
        val needsCompanionObject = context.session.extensionService.declarationGenerators.any {
            it is LombokCompanionObjectContributor && it.needsCompanionObject(declaration.symbol)
        }
        if (!needsCompanionObject) return

        if (!declaration.symbol.hasSerializableCompanion(context.session)) return

        reporter.reportOn(companion.source, LombokFirDiagnostics.COMPANION_OBJECT_SERIALIZABLE_CONFLICT, context)
    }
}
