package org.jetbrains.kotlin.plugin.sandbox.fir.generators

import org.jetbrains.kotlin.fir.FirSession
import org.jetbrains.kotlin.fir.declarations.*
import org.jetbrains.kotlin.fir.declarations.utils.isCompanion
import org.jetbrains.kotlin.fir.expressions.*
import org.jetbrains.kotlin.fir.extensions.*
import org.jetbrains.kotlin.fir.extensions.predicate.LookupPredicate
import org.jetbrains.kotlin.fir.references.impl.FirSimpleNamedReference
import org.jetbrains.kotlin.fir.resolve.getContainingDeclaration
import org.jetbrains.kotlin.fir.symbols.impl.FirClassSymbol
import org.jetbrains.kotlin.fir.types.ConeKotlinType
import org.jetbrains.kotlin.fir.types.FirResolvedTypeRef
import org.jetbrains.kotlin.fir.types.hasResolvedType
import org.jetbrains.kotlin.name.ClassId

class WithCompanionSupertypeGenerator(session: FirSession) : FirSupertypeGenerationExtension(session) {
    companion object {
        private val annotationClassId = ClassId.fromString("org/jetbrains/kotlin/plugin/sandbox/WithCompanion")
        private val annotationPredicate = LookupPredicate.create { annotated(annotationClassId.asSingleFqName()) }
        private val parentAnnotationPredicate = LookupPredicate.create { parentAnnotated(annotationClassId.asSingleFqName()) }
    }

    override fun FirDeclarationPredicateRegistrar.registerPredicates() {
        register(annotationPredicate)
    }

    override fun needTransformSupertypes(declaration: FirClassLikeDeclaration): Boolean {
        // If companion object was generated by 'WithCompanionDeclarationGenerator'...
        return declaration.symbol.origin.toPluginKey<WithCompanionKey>() != null ||
                // ...or is a source companion object.
                ((declaration as? FirRegularClass)?.isCompanion == true &&
                        session.predicateBasedProvider.matches(parentAnnotationPredicate, declaration))
    }

    override fun computeAdditionalSupertypes(
        classLikeDeclaration: FirClassLikeDeclaration,
        resolvedSupertypes: List<FirResolvedTypeRef>,
        typeResolver: PluginTypeResolver,
    ): List<ConeKotlinType> {
        val owner = findAnnotatedOwner(classLikeDeclaration) ?: return emptyList()
        val annotation = owner.getCompilerRequiredAnnotationByClassId(annotationClassId) ?: return emptyList()
        val argument = (annotation as? FirAnnotationCall)?.argumentList?.arguments ?: return emptyList()
        return argument.flatMap { it.unwrapAndFlattenArgument(flattenArrays = true) }
            .filterIsInstance<FirGetClassCall>()
            .map { it.getTargetType(typeResolver) }
    }

    private fun findAnnotatedOwner(declaration: FirClassLikeDeclaration): FirClassSymbol<*>? {
        if (declaration !is FirRegularClass || !declaration.isCompanion) return null
        val owner = declaration.getContainingDeclaration(session)?.symbol as? FirClassSymbol<*> ?: return null
        return owner.takeIf { session.predicateBasedProvider.matches(annotationPredicate, it) }
    }

    private fun FirGetClassCall.getTargetType(
        typeResolver: PluginTypeResolver,
    ): ConeKotlinType {
        if (hasResolvedType) return getTargetType()!!

        return typeFromQualifierParts(
            isMarkedNullable = false,
            source = source!!,
            typeResolver = typeResolver
        ) {
            fun visitQualifiers(expression: FirExpression) {
                if (expression !is FirPropertyAccessExpression) return
                expression.explicitReceiver?.let { visitQualifiers(it) }
                (expression.calleeReference as? FirSimpleNamedReference)?.name?.let { part(it) }
            }
            visitQualifiers(argument)
        }
    }
}
