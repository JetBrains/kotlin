/** Creates the origins of the nodes generated by the JVM backend. */
class KaptIrOrigins(private val irBuiltIns: IrBuiltIns) {
    internal val irTypeSystem = IrTypeSystemContextImpl(irBuiltIns)

    private val declarationsBySource = mutableMapOf<FirFile, FirDeclarationsBySource>()

    fun create(declaration: IrDeclaration): KaptStubOrigin = when (declaration) {
        is IrClass -> KaptIrClassOrigin(declaration, this)
        is IrField -> KaptIrFieldOrigin(declaration, this)
        is IrFunction -> KaptIrMethodOrigin(declaration, this)
        else -> error("Unexpected declaration: ${declaration.render()}")
    }

    // FIR metadata for [declaration], including generated declarations that only keep source ranges.
    internal fun firMetadataOf(declaration: IrDeclaration): FirMetadataSource? {
        ((declaration as? IrMetadataSourceOwner)?.metadata as? FirMetadataSource)?.let { return it }

        val firFile = (declaration.fileParent.metadata as? FirMetadataSource.File)?.fir ?: return null
        return declarationsBySource
            .getOrPut(firFile) { FirDeclarationsBySource.of(firFile) }
            .findInnermostContaining(declaration.startOffset, declaration.endOffset)
    }

    internal val anyClass: IrClass
        @OptIn(UnsafeDuringIrConstructionAPI::class)
        get() = irBuiltIns.anyClass.owner
}

private class KaptIrSourceAnnotation(private val annotation: IrAnnotation) : KaptSourceAnnotation() {
    override val firAnnotation: FirAnnotation?
        get() = (annotation.source as? FirAnnotationSourceElement)?.fir

    override val typeContainsErrors: Boolean
        get() = annotation.type.containsErrorTypes()

    override val constantValue: ConstantValue<*> by lazy(LazyThreadSafetyMode.NONE) { annotation.toConstantValue() }
}

private fun IrDeclaration.findFirFile(): FirFile? {
    val fromMetadata = when (val metadata = (this as? IrClass)?.metadata) {
        is FirMetadataSource.Class -> metadata.fir.moduleData.session.firProvider.getFirClassifierContainerFileIfAny(metadata.fir.symbol)
        is FirMetadataSource.File -> metadata.fir
        else -> null
    }

    return fromMetadata ?: (fileParent.metadata as? FirMetadataSource.File)?.fir
}

private fun IrDeclaration.position(): KotlinPosition = KotlinPosition(fileParent.fileEntry.name, isRelativePath = false, computeOffset())

private fun IrDeclaration.computeOffset(): Int {
    if (origin == JvmLoweredDeclarationOrigin.SYNTHETIC_METHOD_FOR_PROPERTY_OR_TYPEALIAS_ANNOTATIONS) {
        // `$annotations` functions have -1 offsets in the IR, but we'd like to keep them closer to the accessors of the corresponding
        // property to maintain the order that was used when line information was computed by PSI.
        val getter = findPropertyGetterOrFieldBySyntheticAnnotationsMethod()
        if (getter != null) return getter.startOffset
    }

    // All other functions with -1 offsets are supposed to be synthesized by the compiler and it makes sense for them to be at the end.
    if (startOffset == UNDEFINED_OFFSET) return Int.MAX_VALUE

    // Some declarations are synthesized by the compiler, but their offsets are not -1: enum entries, delegated members.
    // Let's place them at the end as well, as other synthesized declarations.

    if (this is IrFunction && name == SpecialNames.ENUM_GET_ENTRIES && origin == IrDeclarationOrigin.ENUM_CLASS_SPECIAL_MEMBER)
        return Int.MAX_VALUE

    if (origin == IrDeclarationOrigin.DELEGATED_MEMBER)
        return Int.MAX_VALUE

    return startOffset
}

@OptIn(UnsafeDuringIrConstructionAPI::class)
private fun IrDeclaration.findPropertyGetterOrFieldBySyntheticAnnotationsMethod(): IrDeclaration? {
    if (this !is IrSimpleFunction) return null
    for (declaration in parentAsClass.functions + parentAsClass.fields) {
        val property = when (declaration) {
            is IrSimpleFunction -> declaration.correspondingPropertySymbol?.owner
            is IrField -> declaration.correspondingPropertySymbol?.owner
            else -> null
        } ?: continue
        val expectedAnnotationsMethodName =
            JvmAbi.getSyntheticMethodNameForAnnotatedProperty(JvmAbi.getterName(property.name.asString()))
        val extensionReceiver = (declaration as? IrSimpleFunction)?.parameters?.getOrNull(1)
        if (expectedAnnotationsMethodName == name.asString() &&
            extensionReceiver?.type?.erasedUpperBound == parameters.getOrNull(1)?.type?.erasedUpperBound
        ) {
            return declaration
        }
    }
    return null
}

private fun IrDeclaration.sourceAnnotations(): List<KaptSourceAnnotation> = annotations.map(::KaptIrSourceAnnotation)

private class KaptIrClassOrigin(val declaration: IrClass, private val origins: KaptIrOrigins) : KaptClassOrigin() {
    override val firFile: FirFile? get() = declaration.findFirFile()
    override val position: KotlinPosition get() = declaration.position()
    override val firSource: KtSourceElement? get() = origins.firMetadataOf(declaration)?.source
    override val sourceAnnotations: List<KaptSourceAnnotation> by lazy(LazyThreadSafetyMode.NONE) { declaration.sourceAnnotations() }

    override val packageFqName: FqName get() = declaration.fileParent.packageFqName
    override val simpleName: String get() = declaration.name.asString()
    override val isNested: Boolean get() = declaration.parent is IrClass
    override val isInner: Boolean get() = declaration.isInner
    override val isEnumClass: Boolean get() = declaration.isEnumClass
    override val isNestedInInterface: Boolean get() = (declaration.parent as? IrClass)?.kind == ClassKind.INTERFACE
    override val firClass: FirClass? get() = (declaration.metadata as? FirMetadataSource.Class)?.fir

    override fun toString(): String = declaration.render()
}

private class KaptIrFieldOrigin(val declaration: IrField, private val origins: KaptIrOrigins) : KaptFieldOrigin() {
    override val firFile: FirFile? get() = declaration.findFirFile()
    override val position: KotlinPosition get() = declaration.position()
    override val firSource: KtSourceElement? get() = origins.firMetadataOf(declaration)?.source
    override val sourceAnnotations: List<KaptSourceAnnotation> by lazy(LazyThreadSafetyMode.NONE) { declaration.sourceAnnotations() }

    override val typeSource: KaptTypeSource
        get() {
            val typeRef = when (val metadata = origins.firMetadataOf(declaration)) {
                is FirMetadataSource.Property -> metadata.fir.returnTypeRef
                is FirMetadataSource.Field -> metadata.fir.returnTypeRef
                else -> null
            }
            val typeMappingMode = if (declaration.correspondingPropertySymbol?.owner?.isVar == true) {
                MethodSignatureMapper.getTypeMappingModeForParameter(origins.irTypeSystem, declaration, declaration.type)
            } else {
                MethodSignatureMapper.getTypeMappingModeForReturnType(origins.irTypeSystem, declaration, declaration.type)
            }
            return KaptTypeSource(declaration.type.containsErrorTypes(), typeRef, typeMappingMode)
        }

    override val firInitializer: FirExpression?
        get() = when (val metadata = declaration.metadata) {
            is FirMetadataSource.Field -> metadata.fir.initializer
            is FirMetadataSource.Property -> metadata.fir.initializer
            else -> null
        }

    override val firProperty: FirProperty?
        get() = (declaration.metadata as? FirMetadataSource.Property)?.fir

    override val isTypeEnumInCompanion: Boolean
        get() = declaration.type.classOrNull?.owner?.let { it.isEnumClass && it.isInsideCompanionObject() } == true

    override fun toString(): String = declaration.render()
}

private fun IrDeclaration.isInsideCompanionObject(): Boolean {
    val parent = parent as? IrDeclaration ?: return false
    if (parent is IrClass && parent.isCompanion) return true
    return parent.isInsideCompanionObject()
}

private class KaptIrMethodOrigin(val declaration: IrFunction, private val origins: KaptIrOrigins) : KaptMethodOrigin() {
    override val firFile: FirFile? get() = declaration.findFirFile()
    override val position: KotlinPosition get() = declaration.position()
    override val firSource: KtSourceElement? get() = origins.firMetadataOf(declaration)?.source
    override val isConstructor: Boolean get() = declaration is IrConstructor
    override val sourceAnnotations: List<KaptSourceAnnotation> by lazy(LazyThreadSafetyMode.NONE) { declaration.sourceAnnotations() }

    override val isJvmOverride: Boolean
        get() = declaration is IrSimpleFunction && declaration.isJvmOverride()

    // @JvmExposeBoxed generates an exposed function, which is not an override.
    private fun IrSimpleFunction.isJvmOverride(): Boolean = when {
        overriddenSymbols.isEmpty() -> false
        !hasAnnotation(JvmStandardClassIds.JVM_EXPOSE_BOXED_ANNOTATION_FQ_NAME) -> true
        else -> overriddenSymbols.any { it.owner.name == name }
    }

    override val parameterNames: List<String?>
        get() = declaration.parameters.filterNot { it.kind == IrParameterKind.DispatchReceiver }.map { it.name.identifierOrNullIfSpecial }

    override val superConstructorArgumentValues: List<Any?>?
        get() {
            val superClass = declaration.parentAsClass.getNonErrorSuperClassNotAny()
            val superClassConstructor =
                superClass.constructors.find {
                    (it.visibility == DescriptorVisibilities.PUBLIC || it.visibility == DescriptorVisibilities.PROTECTED) &&
                            it.origin != JvmLoweredDeclarationOrigin.SYNTHETIC_ACCESSOR_FOR_HIDDEN_CONSTRUCTOR
                } ?: return null

            return superClassConstructor.parameters.map { param ->
                IrConstImpl.defaultValueForType(UNDEFINED_OFFSET, UNDEFINED_OFFSET, param.type).value
            }
        }

    private fun IrClass.getNonErrorSuperClassNotAny(): IrClass {
        // FIR keeps error supertypes
        for (supertype in superTypes) {
            if (supertype !is IrErrorType && !supertype.isAny()) {
                val superclass = supertype.classOrNull?.owner ?: continue
                if (superclass.isClass || superclass.isEnumClass) return superclass
            }
        }
        return origins.anyClass
    }

    @OptIn(SymbolInternals::class)
    private val firCallable: FirCallableDeclaration?
        get() = when (val metadata = origins.firMetadataOf(declaration)) {
            is FirMetadataSource.Function -> metadata.fir
            is FirMetadataSource.Property -> metadata.fir
            is FirMetadataSource.Field -> metadata.fir
            else -> null
        }

    override val returnTypeSource: KaptTypeSource
        get() {
            val firCallable = firCallable
            val returnTypeReference = when (firCallable) {
                is FirPropertyAccessor if declaration.isGetter -> firCallable.returnTypeRef
                is FirProperty if declaration.isGetter -> firCallable.returnTypeRef
                is FirFunction -> firCallable.returnTypeRef
                else -> null
            }
            val typeMappingMode =
                MethodSignatureMapper.getTypeMappingModeForReturnType(origins.irTypeSystem, declaration, declaration.returnType)
            return KaptTypeSource(declaration.returnType.containsErrorTypes(), returnTypeReference, typeMappingMode)
        }

    @OptIn(SymbolInternals::class)
    override fun parameterTypeSource(index: Int, parameterCount: Int): KaptTypeSource? {
        val irValueParameters = declaration.parameters.filter { it.kind == IrParameterKind.Regular }
        val contextParameters = declaration.parameters.filter { it.kind == IrParameterKind.Context }
        val extensionReceiver = declaration.parameters.find { it.kind == IrParameterKind.ExtensionReceiver }
        val firCallable = firCallable
        val firProperty = when (firCallable) {
            is FirPropertyAccessor -> firCallable.propertySymbol.fir
            is FirProperty -> firCallable
            else -> null
        }

        fun source(type: IrType, typeRef: FirTypeRef?): KaptTypeSource =
            KaptTypeSource(
                type.containsErrorTypes(), typeRef,
                MethodSignatureMapper.getTypeMappingModeForParameter(origins.irTypeSystem, declaration, type),
            )

        return when {
            declaration.isGetter -> when {
                index < contextParameters.size ->
                    source(contextParameters[index].type, firProperty?.contextParameters?.getOrNull(index)?.returnTypeRef)
                irValueParameters.isEmpty() && index == contextParameters.size ->
                    source(extensionReceiver?.type ?: declaration.returnType, firProperty?.receiverParameter?.typeRef)
                else -> null
            }
            declaration.isSetter -> when {
                index < contextParameters.size ->
                    source(contextParameters[index].type, firProperty?.contextParameters?.getOrNull(index)?.returnTypeRef)
                index == contextParameters.size && extensionReceiver != null ->
                    source(extensionReceiver.type, firProperty?.receiverParameter?.typeRef)
                irValueParameters.size != 1 -> null
                index == (if (extensionReceiver == null) 0 else 1) + contextParameters.size ->
                    source(irValueParameters[0].type, firProperty?.returnTypeRef)
                else -> null
            }
            else -> {
                val offset = (if (extensionReceiver == null) 0 else 1) + contextParameters.size
                when {
                    index < contextParameters.size ->
                        source(contextParameters[index].type, firCallable?.contextParameters?.getOrNull(index)?.returnTypeRef)
                    extensionReceiver != null && index == contextParameters.size ->
                        source(extensionReceiver.type, firCallable?.receiverParameter?.typeRef)
                    irValueParameters.size + offset == parameterCount -> {
                        val valueParameterIndex = index - offset
                        val irParameter = irValueParameters[valueParameterIndex]
                        val sourceFunction = firCallable as? FirFunction
                        val sourceReturnType = sourceFunction?.returnTypeRef
                        if (sourceFunction != null && sourceReturnType != null && isContinuationParameter(irParameter)) {
                            KaptTypeSource(
                                irParameter.type.containsErrorTypes(), sourceReturnType,
                                MethodSignatureMapper.getTypeMappingModeForParameter(origins.irTypeSystem, declaration, irParameter.type),
                                isContinuation = true,
                            )
                        } else {
                            source(irParameter.type, sourceFunction?.valueParameters?.getOrNull(valueParameterIndex)?.returnTypeRef)
                        }
                    }
                    else -> null
                }
            }
        }
    }

    private fun isContinuationParameter(parameter: IrValueParameter): Boolean =
        parameter.name.asString() == SUSPEND_FUNCTION_COMPLETION_PARAMETER_NAME &&
                parameter.origin == JvmLoweredDeclarationOrigin.CONTINUATION_CLASS

    override fun toString(): String = declaration.render()
}
