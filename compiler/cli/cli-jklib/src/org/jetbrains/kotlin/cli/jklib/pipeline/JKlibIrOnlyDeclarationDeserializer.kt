/**
 * Deserializes, from the main IR of a dependency KLIB, the header of a declaration that exists only in IR.
 *
 * The first compilation phase adds declarations that the pre-processed inline function bodies refer to, most notably the
 * synthetic accessors generated by `OuterThisInInlineFunctionsSpecialAccessorLowering` and `SyntheticAccessorLowering`. They are
 * serialized into the IR of the KLIB, but not into its metadata, which is produced from FIR before those lowerings run. The lazy
 * FIR2IR declarations, which are built from the metadata, therefore don't include them.
 *
 * Only the header of the declaration is deserialized: its body belongs to the dependency, which compiles it itself. The references
 * in that header are resolved with [resolvePublicSymbol], so that it refers to the declarations of the running compilation.
 */
internal class JKlibIrOnlyDeclarationDeserializer(
    private val irBuiltIns: IrBuiltIns,
    private val libraries: List<KotlinLibrary>,
    private val resolvePublicSymbol: (IdSignature, BinarySymbolData.SymbolKind) -> IrSymbol?,
) {
    private val irInterner = IrInterningService()
    private val fileEntryDeserializer = FileEntryDeserializer(irInterner)
    private val symbolTable = SymbolTable(signaturer = null, irBuiltIns.irFactory)
    private val libraryIndices = HashMap<KotlinLibrary, Map<IdSignature, TopLevelDeclaration>>()
    private val module = IrModuleFragmentImpl(ErrorModuleDescriptor)

    /**
     * The dependency KLIBs where [deserializeTopLevel] looks the declarations up.
     *
     * A declaration exists only in the IR of a KLIB when the first compilation phase generated it, for example a synthetic accessor
     * that lets a non-private inline function call the private members of the same KLIB. A KLIB without inline functions has no such
     * declarations, so it is skipped.
     *
     * All the KLIBs with inline functions are searched, not only the one declaring the function being inlined. If an inline function of
     * `a` calls an inline function of `b`, the body of the function of `a` may refer to the synthetic accessors of `b`.
     */
    private val librariesWithInlineFunctions: List<KotlinLibrary> by lazy {
        libraries.filter { it.inlinableFunctionsIr != null }
    }

    /**
     * Returns the member of [enclosingClass] with the given [signature], deserialized from the KLIB [enclosingClass] comes from,
     * or `null` if there is no such member.
     */
    fun deserializeMember(enclosingClass: IrClass, signature: IdSignature): IrDeclaration? {
        val library = (enclosingClass.source as? KlibDeserializedContainerSource)?.klib ?: return null
        val topLevel = indexOf(library)[signature.topLevelSignature()] ?: return null
        val proto = topLevel.file.findMember(topLevel.proto, signature) ?: return null
        return topLevel.file.declarationDeserializer
            .deserializeDeclaration(proto, parentStart = null)
            .also {
                it.parent = enclosingClass
                enclosingClass.declarations += it
            }
    }

    /**
     * Returns the top-level declaration with the given [signature], deserialized from the first of [librariesWithInlineFunctions]
     * that declares it, or `null` if none does.
     *
     * Unlike a class member, a top-level declaration has no lazy container that tells which KLIB it comes from, so the candidate
     * KLIBs are searched one after the other.
     */
    fun deserializeTopLevel(signature: IdSignature): IrDeclaration? {
        val topLevel = librariesWithInlineFunctions.firstNotNullOfOrNull { indexOf(it)[signature] } ?: return null
        // The file annotations, `@JvmName` and `@JvmMultifileClass` in particular, determine the file facade of the declaration.
        topLevel.file.deserializeFileAnnotations()
        return topLevel.file.declarationDeserializer
            .deserializeDeclaration(topLevel.proto, parentStart = null)
            // Like the IR linker does, parent the top-level declarations to their file, from which the file facade they belong
            // to is computed.
            .also {
                it.parent = topLevel.file.irFile
                topLevel.file.irFile.declarations += it
            }
    }

    private fun indexOf(library: KotlinLibrary): Map<IdSignature, TopLevelDeclaration> =
        libraryIndices.getOrPut(library) {
            val ir = library.ir ?: return@getOrPut emptyMap()
            buildMap {
                for (fileIndex in 0 until ir.irFileCount) {
                    val file = FileDeserializer(ir, fileIndex)
                    for (index in file.fileProto.declarationIdList) {
                        put(file.symbolDeserializer.deserializeIdSignature(index), TopLevelDeclaration(file, index))
                    }
                }
            }
        }

    private class TopLevelDeclaration(val file: FileDeserializer, val index: Int) {
        val proto: ProtoDeclaration
            get() = file.reader.declaration(index)
    }

    private inner class FileDeserializer(ir: KlibIrComponent, fileIndex: Int) {
        val reader = IrLibraryFileFromBytes(IrKlibBytesSource(ir, fileIndex))

        val fileProto: ProtoFile = ProtoFile.parseFrom(ir.irFile(fileIndex).codedInputStream, ExtensionRegistryLite.getEmptyRegistry())

        /**
         * The file the top-level declarations are parented to, created the same way the IR linker does. Its file annotations are
         * only deserialized by [deserializeFileAnnotations].
         */
        val irFile: IrFile = reader.createFile(module, fileProto, fileEntryDeserializer)

        val symbolDeserializer = IrSymbolDeserializer(
            symbolTable,
            reader,
            irFile.symbol,
            enqueueLocalTopLevelDeclaration = {},
            irInterner,
            deserializePublicSymbolWithOwnerInUnknownFile = { signature, symbolKind ->
                resolvePublicSymbol(signature, symbolKind) ?: referenceUnbound(signature, symbolKind)
            },
        )

        val declarationDeserializer by lazy {
            IrDeclarationDeserializer(
                unitType = irBuiltIns.unitType,
                nothingType = irBuiltIns.nothingType,
                symbolTable = symbolTable,
                irFactory = irBuiltIns.irFactory,
                libraryFile = reader,
                parent = irFile,
                settings = IrDeserializationSettings(
                    // Only the header is needed: synthetic accessors are never inline.
                    deserializeFunctionBodies = DeserializeFunctionBodies.ONLY_INLINE,
                    nullableAnyAsAnnotationConstructorCallType = irBuiltIns.anyNType,
                ),
                symbolDeserializer = symbolDeserializer,
                onDeserializedClass = { _, signature ->
                    // The fake overrides of a deserialized class would have to be built, but only function headers are ever
                    // deserialized: their bodies are skipped, and their signatures can't contain local types.
                    error("Unexpected deserialization of class $signature")
                },
                needToDeserializeFakeOverrides = { false },
                specialProcessingForMismatchedSymbolKind = null,
                irInterner = irInterner,
                fileEntryDeserializer = fileEntryDeserializer,
            )
        }

        private val fileDeserializer by lazy {
            IrFileDeserializerImpl(irFile, reader, fileProto, symbolDeserializer, declarationDeserializer)
        }

        /** Deserializes the annotations of [irFile] the first time it is called, like the IR linker does. */
        fun deserializeFileAnnotations() {
            fileDeserializer.deserializeFileImplicitDataIfFirstUse()
        }

        /** Looks for the declaration with the given [signature] among the members of [proto]. */
        fun findMember(proto: ProtoDeclaration, signature: IdSignature): ProtoDeclaration? {
            if (proto.declaratorCase != DeclaratorCase.IR_CLASS) return null
            for (member in proto.irClass.declarationList) {
                if (signatureOf(member) == signature) return member
                findMember(member, signature)?.let { return it }
            }
            return null
        }

        private fun signatureOf(proto: ProtoDeclaration): IdSignature? {
            val symbol = when (proto.declaratorCase) {
                DeclaratorCase.IR_FUNCTION -> proto.irFunction.base.base.symbol
                DeclaratorCase.IR_CONSTRUCTOR -> proto.irConstructor.base.base.symbol
                DeclaratorCase.IR_PROPERTY -> proto.irProperty.base.symbol
                DeclaratorCase.IR_CLASS -> proto.irClass.base.symbol
                else -> return null
            }
            return symbolDeserializer.deserializeIdSignature(BinarySymbolData.decode(symbol).signatureId)
        }
    }

    private fun referenceUnbound(signature: IdSignature, symbolKind: BinarySymbolData.SymbolKind): IrSymbol =
        when (symbolKind) {
            BinarySymbolData.SymbolKind.CLASS_SYMBOL -> symbolTable.referenceClass(signature)
            BinarySymbolData.SymbolKind.CONSTRUCTOR_SYMBOL -> symbolTable.referenceConstructor(signature)
            BinarySymbolData.SymbolKind.FUNCTION_SYMBOL -> symbolTable.referenceSimpleFunction(signature)
            BinarySymbolData.SymbolKind.PROPERTY_SYMBOL -> symbolTable.referenceProperty(signature)
            BinarySymbolData.SymbolKind.TYPE_PARAMETER_SYMBOL -> symbolTable.referenceTypeParameter(signature)
            else -> error("Unexpected reference to $symbolKind $signature")
        }
}
