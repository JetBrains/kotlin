package org.jetbrains.kotlin.diagnostics

/**
 * Standard parse-tree agnostic positioning strategies of diagnostics with source elements.
 * Their implementations for the concrete parse trees are provided by [ParseTreeKind.positioningStrategy].
 *
 * It's an abstract class rather than an enum, so that plugins can extend it with their own strategies in the future.
 */
