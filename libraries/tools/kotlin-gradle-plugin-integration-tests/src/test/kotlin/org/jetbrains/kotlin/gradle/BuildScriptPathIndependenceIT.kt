package org.jetbrains.kotlin.gradle

import org.gradle.api.artifacts.repositories.MavenArtifactRepository
import org.gradle.util.GradleVersion
import org.jetbrains.kotlin.gradle.testbase.*
import org.jetbrains.kotlin.testFederation.MustRunOnChangesInGradle
import org.junit.jupiter.api.DisplayName
import org.junit.jupiter.api.io.TempDir
import java.io.File
import java.nio.file.Path
import kotlin.io.path.readLines
import kotlin.io.path.readText
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith

/**
 * Gradle caches compiled build scripts by their text, so test-specific absolute paths in scripts force a recompilation in every test.
 */
@JvmGradlePluginTests
@MustRunOnChangesInGradle
@DisplayName("Build scripts are independent of test temp directories")
@GradleTestVersions(minVersion = TestVersions.Gradle.MAX_SUPPORTED)
class BuildScriptPathIndependenceIT : KGPBaseTest() {

    @GradleTest
    @DisplayName("Scripts generated by the test framework contain no test temp directories")
    fun generatedScriptsContainNoTestTempDirectories(gradleVersion: GradleVersion, @TempDir buildCacheDir: Path) {
        listOf("empty", "emptyKts").forEach { template ->
            val localRepo = defaultLocalRepo(gradleVersion).toFile()
            project(template, gradleVersion) {
                settingsBuildScriptInjection {
                    val repositoryDirs = settings.dependencyResolutionManagement.repositories
                        .withType(MavenArtifactRepository::class.java)
                        .filter { it.url.scheme == "file" }
                        .map { File(it.url).canonicalFile }
                    check(localRepo.canonicalFile in repositoryDirs) { "Local repository $localRepo is missing from $repositoryDirs" }
                }
                buildScriptInjection {
                    project.tasks.register("noop")
                }
                enableLocalBuildCache(buildCacheDir)

                build("noop")

                assertEquals(emptyList(), findBuildScriptPathReferences(projectPath))
            }
        }
    }

    @GradleTest
    @DisplayName("Settings scripts are identical for projects with different local repositories")
    fun settingsScriptsAreIdenticalForDifferentLocalRepositories(gradleVersion: GradleVersion) {
        val first = project("empty", gradleVersion, localRepoDir = workingDir.resolve("first-repo"))
        val second = project("empty", gradleVersion, localRepoDir = workingDir.resolve("second-repo"))

        assertEquals(first.settingsGradle.readText(), second.settingsGradle.readText())
    }

    @GradleTest
    @DisplayName("Build fails when a build script references a test temp directory")
    fun buildFailsWhenBuildScriptReferencesTestTempDirectory(gradleVersion: GradleVersion) {
        project("empty", gradleVersion) {
            val marker = "// ${workingDir.resolve("marker")}"
            buildGradle.append("\n$marker\n")
            val markerLine = buildGradle.readLines().indexOf(marker) + 1

            val failure = assertFailsWith<AssertionError> { build("help") }

            assertEquals(
                listOf("  build.gradle:$markerLine: $marker"),
                failure.message?.lines()?.filter { "build.gradle:" in it },
            )
        }
    }
}
