package org.jetbrains.kotlin.gradle.plugin.mpp.apple

import org.gradle.api.DefaultTask
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault
import org.jetbrains.kotlin.gradle.plugin.diagnostics.KotlinToolingDiagnostics
import org.jetbrains.kotlin.gradle.plugin.diagnostics.UsesKotlinToolingDiagnostics
import org.jetbrains.kotlin.gradle.targets.js.npm.SemVer

/**
 * Checks that Xcode builds against a deployment target the Swift code generated by Swift Export can compile against.
 *
 * All properties are optional: Xcode does not always tell us the deployment target, and not every platform has a
 * known minimum. In both cases there is nothing to check.
 */
@DisableCachingByDefault(because = "Validation task, no outputs")
internal abstract class ValidateSwiftExportDeploymentTargetTask : DefaultTask(), UsesKotlinToolingDiagnostics {

    @get:Input
    @get:Optional
    abstract val deploymentTargetSettingName: Property<String>

    @get:Input
    @get:Optional
    abstract val deploymentTarget: Property<String>

    @get:Input
    @get:Optional
    abstract val minimumDeploymentTarget: Property<String>

    @TaskAction
    fun validate() {
        val settingName = deploymentTargetSettingName.orNull ?: return
        val deploymentTarget = deploymentTarget.orNull ?: return
        val minimumDeploymentTarget = minimumDeploymentTarget.orNull ?: return

        if (SemVer.from(deploymentTarget, loose = true) >= SemVer.from(minimumDeploymentTarget, loose = true)) return

        reportDiagnostic(
            KotlinToolingDiagnostics.SwiftExportMinimumDeployTargetError(
                deploymentTargetSettingName = settingName,
                actualDeploymentTarget = deploymentTarget,
                minimumDeploymentTarget = minimumDeploymentTarget,
            )
        )
    }
}
