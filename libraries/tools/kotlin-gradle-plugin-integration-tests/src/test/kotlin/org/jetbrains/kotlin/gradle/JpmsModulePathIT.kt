@DisplayName("KT-90678: module path of a compilation with module-info.java")
@JvmGradlePluginTests
@JdkVersions(versions = [JavaVersion.VERSION_17])
class JpmsModulePathIT : KGPBaseTest() {

    override val defaultBuildOptions: BuildOptions
        get() = super.defaultBuildOptions.copy(compilerArgumentsLogLevel = "warning")

    @DisplayName("Modules are passed with -Xmodule-path, and all dependencies with -classpath")
    @GradleWithJdkTest
    fun modulesOnModulePath(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            build(":application:assemble") {
                val args = compileKotlinArguments()
                assertEquals(
                    listOf("kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar"),
                    args.javaModulePath.fileNames().sorted(),
                )
                assertClasspathUnchanged(args)
            }
        }
    }

    @DisplayName("No module path is passed when inferModulePath is disabled")
    @GradleWithJdkTest
    fun inferModulePathDisabled(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.appendText(
                """
                |
                |tasks.compileJava { modularity.inferModulePath.set(false) }
                """.trimMargin()
            )
            build(":application:compileKotlin") {
                val args = compileKotlinArguments()
                assertNull(args.javaModulePath)
                assertClasspathUnchanged(args)
            }
        }
    }

    @DisplayName("No module path is passed with module-info.java below a Java source root")
    @GradleWithJdkTest
    fun moduleInfoBelowSourceRoot(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            val javaSources = subProject("application").javaSourcesDir()
            javaSources.resolve("module-info.java").moveTo(javaSources.resolve("org/gradle/sample/app/module-info.java"))
            build(":application:compileKotlin") {
                assertNull(compileKotlinArguments().javaModulePath)
            }
        }
    }

    @DisplayName("Modules are passed when module-info.java is excluded from compileJava, as in JavaCompile")
    @GradleWithJdkTest
    fun moduleInfoExcludedFromCompileJava(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.appendText(
                """
                |
                |tasks.compileJava { exclude("module-info.java") }
                """.trimMargin()
            )
            val modulePath = listOf("kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar")
            build(":application:compileKotlin") {
                assertEquals(modulePath, compileKotlinArguments().javaModulePath.fileNames().sorted())
            }
            build(":application:compileJava", buildOptions = buildOptions.copy(logLevel = LogLevel.DEBUG)) {
                assertEquals(modulePath, javacModulePath().fileNames().sorted())
            }
        }
    }

    @DisplayName("A Java source directory generated by a task leaves the module path as it is")
    @GradleWithJdkTest
    fun generatedJavaSourceDirectory(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.appendText(
                """
                |
                |abstract class GenerateJava : DefaultTask() {
                |    @get:OutputDirectory
                |    abstract val outputDirectory: DirectoryProperty
                |
                |    @TaskAction
                |    fun generate() {
                |        outputDirectory.get().asFile.mkdirs()
                |    }
                |}
                |
                |val generateJava = tasks.register<GenerateJava>("generateJava") {
                |    outputDirectory.set(layout.buildDirectory.dir("generated"))
                |}
                |
                |sourceSets.main { java.srcDir(generateJava.flatMap { it.outputDirectory }) }
                """.trimMargin()
            )
            build(":application:compileKotlin") {
                assertTasksExecuted(":application:generateJava")
                assertEquals(
                    listOf("kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar"),
                    compileKotlinArguments().javaModulePath.fileNames().sorted(),
                )
            }
        }
    }

    @DisplayName("No dependency is added to compileKotlin when a Java source directory is generated after it")
    @GradleWithJdkTest
    fun javaSourcesGeneratedAfterCompileKotlin(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.appendText(
                """
                |
                |val generateJava = tasks.register("generateJava") {
                |    dependsOn(tasks.compileKotlin)
                |    val outputDirectory = layout.buildDirectory.dir("generated")
                |    outputs.dir(outputDirectory)
                |    doLast { outputDirectory.get().asFile.mkdirs() }
                |}
                |
                |sourceSets.main { java.srcDir(generateJava) }
                |tasks.compileKotlin { setSource(files("src/main/kotlin", "src/main/java")) }
                """.trimMargin()
            )
            build(":application:compileJava") {
                assertTasksExecuted(":application:compileKotlin", ":application:generateJava")
                assertEquals(
                    listOf("kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar"),
                    compileKotlinArguments().javaModulePath.fileNames().sorted(),
                )
            }
        }
    }

    @DisplayName("No module path is passed when kotlinc compiles an unnamed module")
    @GradleWithJdkTest
    fun kotlinUnnamedModule(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.appendText(
                """
