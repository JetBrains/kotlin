package org.jetbrains.kotlin.wasm.test.tools

import java.io.File
import java.nio.file.Files

/**
 * Turns a WASI core module produced by a test into a WASI 0.2 component, which is the only form a host can run:
 * the standard library imports `wasi:*` 0.2 interfaces directly.
 *
 * This is `wasm-tools component embed` with the standard library's WIT, plus a world that exports the entry point the
 * test is going to invoke, followed by `wasm-tools component new`.
 *
 * Configuration (all optional):
 *  - `wasm.tools.path` - `wasm-tools` executable, provisioned by the `wasm-tools-configuration` plugin,
 *  - `kotlin.wasm.wit.dir` - the standard library's WIT directory, by default found relative to the repository root.
 */
internal object WasiComponentizer {
    /** Entry point of the box test runner, see `wasiBoxTestRun.kt`. */
    const val BOX_ENTRY_POINT: String = "start-test"

    /** Entry point of the unit test runner, generated by the Wasm backend (`wasmWasiUnitTestsExportName`). */
    const val UNIT_TESTS_ENTRY_POINT: String = "start-unit-tests"

    private const val WIT_PACKAGE = "kotlin-stdlib:wasip2"

    private val wasmTools: String = System.getProperty("wasm.tools.path") ?: "wasm-tools"

    private val hackDir: File by lazy {
        val fromProperty = System.getProperty("kotlin.wasm.test.root.out.dir")?.let(::File)
        File(fromProperty ?: File("build"), "wasip2-components").also { it.mkdirs() }
    }

    /**
     * The standard library's WIT, plus one world per entry point, prepared once per JVM.
     *
     * Tests run in several forked JVMs in parallel (`kotlin.test.junit5.maxParallelForks`), so this is a private
     * directory per JVM rather than a shared one that would have to be wiped and re-created.
     */
    private val witDir: File by lazy {
        val stdlibWit = System.getProperty("kotlin.wasm.wit.dir")?.let(::File) ?: findStdlibWitDir()
        check(stdlibWit.isDirectory) { "stdlib WIT directory not found at ${stdlibWit.absolutePath}" }

        val target = Files.createTempDirectory(hackDir.toPath(), "wit-").toFile()
        stdlibWit.copyRecursively(target, overwrite = true)
        Runtime.getRuntime().addShutdownHook(Thread { target.deleteRecursively() })

        val worlds = listOf(BOX_ENTRY_POINT, UNIT_TESTS_ENTRY_POINT).joinToString("\n\n") { entryPoint ->
            """
            world ${worldOf(entryPoint)} {
                include wasi:io/imports@0.2.12;
                include wasi:random/imports@0.2.12;
                include wasi:clocks/imports@0.2.12;
                include wasi:cli/imports@0.2.12;

                export $entryPoint: func();
            }
            """.trimIndent()
        }
        File(target, "test-worlds.wit").writeText(
            """
            package $WIT_PACKAGE@2.5.0;

            // Like the `wasip2` world, but exporting a test entry point instead of `wasi:cli/run`, since test
            // binaries have no `main`. Exports of the module that the world does not mention are dropped.
            $worlds
            """.trimIndent()
        )
        target
    }

    private fun worldOf(entryPoint: String) = "wasip2-$entryPoint"

    private fun findStdlibWitDir(): File {
        val relative = "libraries/stdlib/wasm/wasi/internal/wit"
        var candidate: File? = File("").absoluteFile
        while (candidate != null) {
            val wit = File(candidate, relative)
            if (wit.isDirectory) return wit
            candidate = candidate.parentFile
        }
        error("Could not find '$relative' in any parent of ${File("").absolutePath}; set -Dkotlin.wasm.wit.dir=...")
    }

    /**
     * Builds a component out of [coreModule], exporting [entryPoint], and returns it. Writes the component next to
     * the original module.
     */
    fun componentize(coreModule: File, entryPoint: String): File {
        check(coreModule.isFile) { "${coreModule.absolutePath} does not exist" }

        val embedded = File(coreModule.parentFile, "${coreModule.nameWithoutExtension}.embedded.wasm")
        val component = File(coreModule.parentFile, "${coreModule.nameWithoutExtension}.component.wasm")
        runWasmTools(
            "component", "embed", witDir.absolutePath, coreModule.absolutePath,
            "--world", "$WIT_PACKAGE/${worldOf(entryPoint)}", "-o", embedded.absolutePath,
        )
        runWasmTools("component", "new", embedded.absolutePath, "-o", component.absolutePath)
        return component
    }

    private fun runWasmTools(vararg arguments: String) {
        val command = listOf(wasmTools) + arguments
        val process = ProcessBuilder(command).redirectErrorStream(true).start()
        val output = process.inputStream.bufferedReader().readText()
        val exitCode = process.waitFor()
        check(exitCode == 0) {
            "Command \"${command.joinToString(" ") { escapeShellArgument(it) }}\" " +
                    "terminated with exit code $exitCode\nOUTPUT:\n$output\n---"
        }
    }
}
