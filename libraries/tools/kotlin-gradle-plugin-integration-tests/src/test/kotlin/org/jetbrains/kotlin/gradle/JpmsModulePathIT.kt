                |tasks.compileKotlin { setSource(files("src/main/kotlin")) }
                """.trimMargin()
            )
            build(":application:compileKotlin") {
                assertNull(compileKotlinArguments().javaModulePath)
            }
        }
    }

    @DisplayName("Modules are passed when javaPackagePrefix is set, since kotlinc still compiles a named module")
    @GradleWithJdkTest
    fun javaPackagePrefix(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.appendText(
                """
                |
                |tasks.compileKotlin { javaPackagePrefix = "org.gradle.sample.app" }
                """.trimMargin()
            )
            build(":application:compileKotlin") {
                assertEquals(
                    listOf("kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar"),
