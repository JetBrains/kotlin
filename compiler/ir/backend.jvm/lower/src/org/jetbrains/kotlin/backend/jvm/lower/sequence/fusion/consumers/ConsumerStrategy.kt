/**
 * Each strategy has 3 parts:
 * 1. initialDeclarations - creates variables that will be used in the consumer body
 * 2. getConsumerBuilder - creates the consumer body dependent on the variable given by the producer/transformer
 * 3. createResult - creates the result of the producer body
 *
 * IR generated by getConsumerBuilder returns a Boolean to the producer/transformer.
 * If the Boolean is `false`, the producer/transformer will stop iterating over the sequence.
 */
internal abstract class ConsumerStrategy(val data: ConsumerData, val expression: IrExpression) {
    abstract fun getInitialDeclarations(): List<IrVariable>

    abstract fun getConsumerBuilder(): ConsumerBodyBuilder?

    abstract fun createResult(): IrExpression
}

internal fun ConsumerStrategy.createSequenceReplacement(): SequenceReplacement? =
    getConsumerBuilder()?.let { SequenceReplacement(getInitialDeclarations(), it, createResult()) }

internal data class ConsumerData(
    val context: JvmBackendContext,
    val builder: IrBuilderWithScope,
    val parent: IrDeclarationParent,
    val sequenceData: SequenceData,
)

internal fun createConsumerStrategy(
    expression: IrBlock,
    data: ConsumerData,
): ConsumerStrategy? {
    val loopData = gatherLoopData(expression, data.parent, data.context) ?: return null
    return ForLoopStrategy(data, loopData, expression)
}

fun IrElement.rebindJumps(
    targetLoop: IrLoop,
    onBreak: (IrBreak) -> IrExpression,
    onContinue: (IrContinue) -> IrExpression
) = transformChildrenVoid(object : IrElementTransformerVoid() {
    override fun visitBreak(jump: IrBreak): IrExpression {
        if (jump.loop == targetLoop) return onBreak(jump)
        return super.visitBreak(jump)
    }

    override fun visitContinue(jump: IrContinue): IrExpression {
        if (jump.loop == targetLoop) return onContinue(jump)
        return super.visitContinue(jump)
    }
})
