                )
            }
        }
    }

    @DisplayName("A module is passed when a plain jar earlier on the classpath has its module name")
    @GradleWithJdkTest
    fun plainJarWithModuleName(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            val application = subProject("application")
            val plainJar = application.projectPath.resolve("libs/org.gradle.sample.utilities.jar")
            plainJar.parent.createDirectories()
            ZipOutputStream(plainJar.outputStream()).use { zip ->
                zip.putNextEntry(ZipEntry("plain/Plain.txt"))
                zip.closeEntry()
            }
            application.buildGradleKts.modify {
                it.replace(
                    "implementation(project(\":utilities\"))",
                    "implementation(files(\"libs/org.gradle.sample.utilities.jar\"))\n    implementation(project(\":utilities\"))",
                )
            }
            // Greeting.kt calls StringUtils, so kotlinc has to resolve the utilities module as javac does
            build(":application:compileKotlin") {
                val args = compileKotlinArguments()
                val classpath = args.classpath.fileNames()
                val plainJar = classpath.indexOf("org.gradle.sample.utilities.jar")
                assertTrue(plainJar >= 0 && plainJar < classpath.indexOf("utilities.jar"), "$classpath")
                assertEquals(
                    listOf("kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar"),
                    args.javaModulePath.fileNames().sorted(),
                )
            }
        }
    }

    @DisplayName("No module path is passed without module-info.java")
    @GradleWithJdkTest
    fun noModuleInfo(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").javaSourcesDir().resolve("module-info.java").deleteExisting()
            build(":application:compileKotlin") {
                val args = compileKotlinArguments()
                assertNull(args.javaModulePath)
                assertClasspathUnchanged(args)
            }
        }
    }

    @DisplayName("A module path in freeCompilerArgs is the only one passed")
    @GradleWithJdkTest
    fun modulePathInFreeCompilerArgs(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.appendText(
                """
                |
                |kotlin.compilerOptions.freeCompilerArgs.addAll(
                |    configurations.compileClasspath.map { listOf("-Xmodule-path=" + it.asPath) }
                |)
                """.trimMargin()
            )
            build(":application:assemble") {
                val modulePathArguments = argumentsStartingWith(":application:compileKotlin", "-Xmodule-path")
                assertEquals(1, modulePathArguments.size, "-Xmodule-path arguments: $modulePathArguments")
                // annotations-13.0.jar is not a module, so only the module path in freeCompilerArgs includes it
                assertEquals(
                    listOf("annotations-13.0.jar", "kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar"),
                    modulePathArguments.single().substringAfter("=").fileNames().sorted(),
                )
                assertClasspathUnchanged(compileKotlinArguments())
            }
        }
    }

    @DisplayName("No module path is inferred with a classpath in freeCompilerArgs")
    @GradleWithJdkTest
    fun classpathInFreeCompilerArgs(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.appendText(
                """
                |
                |kotlin.compilerOptions.freeCompilerArgs.addAll(
                |    configurations.compileClasspath.map { listOf("-classpath=" + it.asPath) }
                |)
                """.trimMargin()
            )
            build(":application:compileKotlin") {
                assertEquals(emptyList(), argumentsStartingWith(":application:compileKotlin", "-Xmodule-path"))
            }
        }
    }

    @DisplayName("The same module path is passed to kapt stub generation")
    @GradleWithJdkTest
    fun kaptStubs(gradleVersion: GradleVersion, providedJdk: JdkVersions.ProvidedJdk) {
        jpmsProject(gradleVersion, providedJdk) {
            subProject("application").buildGradleKts.modify {
                it.replace("id(\"org.jetbrains.kotlin.jvm\")", "id(\"org.jetbrains.kotlin.jvm\")\n    id(\"org.jetbrains.kotlin.kapt\")")
            }
            build(":application:kaptGenerateStubsKotlin") {
                val modulePath = argumentsStartingWith(":application:kaptGenerateStubsKotlin", "-Xmodule-path").single()
                assertEquals(
                    listOf("kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar"),
                    modulePath.substringAfter("=").fileNames().sorted(),
                )
            }
        }
    }

    private fun jpmsProject(
        gradleVersion: GradleVersion,
        providedJdk: JdkVersions.ProvidedJdk,
        test: TestProject.() -> Unit,
    ) = project("jpmsProject", gradleVersion, buildJdk = providedJdk.location) {
        val application = subProject("application")
        application.javaSourcesDir().resolve("module-info.java").modify {
            it.replace("requires org.gradle.sample.utilities;", "requires org.gradle.sample.utilities;\n    requires kotlin.stdlib;")
        }
        application.kotlinSourcesDir().resolve("org/gradle/sample/app").createDirectories().resolve("Greeting.kt").writeText(
            """
            |package org.gradle.sample.app
            |
            |import org.gradle.sample.utilities.StringUtils
            |
            |fun greeting(): String = StringUtils.join(StringUtils.split("Hello, modules"))
            """.trimMargin()
        )
        test()
    }

    @Suppress("DEPRECATION")
    private fun BuildResult.compileKotlinArguments(): K2JVMCompilerArguments =
        extractTaskCompilerArguments<K2JVMCompilerArguments>(":application:compileKotlin")

    private fun BuildResult.javacModulePath(): String? {
        val arguments = javacArgumentsRegex.findAll(output).single().groupValues[1].split(" ")
        return arguments.indexOf("--module-path").takeIf { it >= 0 }?.let { arguments[it + 1] }
    }

    private fun BuildResult.argumentsStartingWith(taskPath: String, prefix: String): List<String> =
        extractTaskCompilerArguments(taskPath).split(" ").filter { it.startsWith(prefix) }

    private fun TestProject.assertClasspathUnchanged(args: K2JVMCompilerArguments) {
        assertEquals(
            listOf("annotations-13.0.jar", "kotlin-stdlib-${buildOptions.kotlinVersion}.jar", "list.jar", "utilities.jar"),
            args.classpath.fileNames().sorted(),
        )
    }

    private fun String?.fileNames(): List<String> =
        orEmpty().split(File.pathSeparator).filter { it.isNotEmpty() }.map { File(it).name }
}

private val javacArgumentsRegex = Regex("""\[DEBUG] \[[^]]*JavaCompiler] Compiler arguments: ([^\r\n]*)""")
