internal fun compileForStubGeneration(
    disposable: Disposable,
    configuration: CompilerConfiguration,
    options: KaptOptions,
    logger: KaptLogger,
    withJdk: Boolean,
    onFrontendOutput: (JvmFrontendPipelineArtifact) -> Boolean = { false },
): KaptContextForStubGeneration? {
    if (options[KaptFlag.HEADER_MODE]) {
        configuration.languageVersionSettings = configuration.languageVersionSettings.withStubGenerationHeaderMode()
    }

    val frontendInput = ConfigurationPipelineArtifact(configuration, disposable)
        .withNewDiagnosticCollector(DiagnosticsCollectorImpl())
    val frontendOutput = JvmFrontendPipelinePhase.executePhase(frontendInput) ?: return null

    if (onFrontendOutput(frontendOutput)) return null

    configuration.perfManager?.notifyPhaseFinished(PhaseType.Analysis)

    if (options[KaptFlag.STUBS_FROM_FIR]) {
        // The exposed variants come from JvmInlineClassLowering, which the FIR generator does not mirror.
        if (!frontendOutput.usesJvmExposeBoxed()) return generateStubsFromFir(frontendOutput, options, logger, withJdk)
        logger.info("@JvmExposeBoxed is used, so stubs are generated by the JVM backend instead of straight from FIR")
    }

    // Every phase is run with a fresh diagnostics collector, because KAPT is expected to compile incomplete code, while each phase
    // early-returns if there are already errors in the collector.
    val fir2IrOutput = JvmFir2IrPipelinePhase.executePhase(
        frontendOutput.withNewDiagnosticCollector(DiagnosticsCollectorImpl()),
        irGenerationExtensions = emptyList(),
    ) ?: return null

    val builderFactory = OriginCollectingClassBuilderFactory(ClassBuilderMode.KAPT3, KaptIrOrigins(fir2IrOutput.result.irBuiltIns))
    val backendInput = fir2IrOutput.withNewDiagnosticCollector(DiagnosticsCollectorImpl())
    backendInput.configuration.put(JvmLoweringsPipelinePhase.customClassBuilderFactory, builderFactory)

    val generationState = JvmCodegenPipelinePhase.executePhase(JvmLoweringsPipelinePhase.executePhase(backendInput)).outputs.singleOrNull() ?: return null

    return KaptContextForStubGeneration(
        options, withJdk, logger, builderFactory.compiledClasses, builderFactory.origins,
        backendInput.configuration,
        generationState.factory,
        frontendOutput.frontendOutput.outputs.flatMap { it.fir },
    )
}

/**
 * Stubs need no function bodies. Pruning would drop declarations stubs must contain; property initializers and accessors are
 * needed for field initializers and backing fields.
 */
private fun LanguageVersionSettings.withStubGenerationHeaderMode(): LanguageVersionSettings {
    val original = this
    return object : LanguageVersionSettings by original {
        @Suppress("UNCHECKED_CAST")
        override fun <T> getFlag(flag: AnalysisFlag<T>): T = when (flag) {
            AnalysisFlags.headerMode, AnalysisFlags.headerModeKeepPropertyBodies -> true as T
            AnalysisFlags.firAggressivePruning -> false as T
            else -> original.getFlag(flag)
        }
    }
}

private fun JvmFrontendPipelineArtifact.usesJvmExposeBoxed(): Boolean {
    if (configuration.languageVersionSettings.getFlag(JvmAnalysisFlags.implicitJvmExposeBoxed)) return true
    return frontendOutput.outputs.any { output ->
        var found = false
        val visitor = object : FirVisitorVoid() {
            override fun visitElement(element: FirElement) {
                if (!found) element.acceptChildren(this)
            }

            override fun visitAnnotation(annotation: FirAnnotation) {
                if (annotation.toAnnotationClassId(output.session) == JvmStandardClassIds.JVM_EXPOSE_BOXED_ANNOTATION_CLASS_ID) found = true
            }

            override fun visitAnnotationCall(annotationCall: FirAnnotationCall) = visitAnnotation(annotationCall)
        }
        output.fir.forEach { it.accept(visitor) }
        found
    }
}

private fun generateStubsFromFir(
    frontendOutput: JvmFrontendPipelineArtifact,
    options: KaptOptions,
    logger: KaptLogger,
    withJdk: Boolean,
): KaptContextForStubGeneration {
    val configuration = frontendOutput.configuration
    val compiledClasses = mutableListOf<ClassNode>()
    val origins = HashMap<Any, KaptStubOrigin>()
    val outputFiles = mutableListOf<OutputFile>()
    // Like the JVM backend, write one module mapping for all modules.
    val packagePartRegistry = PackagePartRegistry()
    for (output in frontendOutput.frontendOutput.outputs) {
        val generator = FirKaptStubGenerator(output.session, output.scopeSession, configuration, packagePartRegistry)
        outputFiles += generator.generate(output.fir).asList()
        compiledClasses += generator.compiledClasses
        origins += generator.origins
    }
    val firFiles = frontendOutput.frontendOutput.outputs.flatMap { it.fir }
    outputFiles += FirKaptModuleMappingFile(configuration, packagePartRegistry, firFiles.mapNotNull { it.sourceFile?.path?.let(::File) })
    return KaptContextForStubGeneration(
        options, withJdk, logger, compiledClasses, origins, configuration, FirKaptOutputFiles(outputFiles), firFiles,
    )
}
