package org.jetbrains.kotlin.wasm.test.tools

import java.io.File
import java.net.URI
import java.nio.file.Files

/**
 * HACK (KT-87723): turns a WASI core module produced by a box test into a WASI 0.2 component, so that it can be run
 * at all: the standard library imports `wasi:*` 0.2 interfaces directly, which no plain core module host provides.
 *
 * Mirrors the hack in `libraries/stdlib/build.gradle.kts` for the stdlib WASI tests:
 *  - `wasm-tools component embed` with the stdlib WIT plus a test-only world that exports the box test entry point
 *    ([ENTRY_POINT]) instead of `wasi:cli/run` (box test binaries have no `main`),
 *  - `wasm-tools component new`, with the stock preview1 reactor adapter for the `wasi_snapshot_preview1` imports
 *    that the test entry point (`proc_exit`) and kotlin-test (`args_get`/`args_sizes_get`) still use.
 *
 * Configuration (all optional):
 *  - `wasm.tools.path` - `wasm-tools` executable, by default looked up on `PATH`,
 *  - `kotlin.wasm.wit.dir` - stdlib WIT directory, by default found relative to the repository root,
 *  - `kotlin.wasm.wasi.adapter` - preview1 adapter, downloaded into `build/` when absent.
 *
 * Delete this together with the entry point rename once the compiler/KGP emit components themselves.
 */
internal object WasiComponentizer {
    /**
     * Box test entry point (`wasiBoxTestRun.kt` / the generated batch launcher); kebab-case, since WIT and
     * `wasmtime --invoke` (WAVE) reject camelCase.
     */
    const val BOX_ENTRY_POINT: String = "start-test"

    /**
     * Unit test runner entry point, needed by the grouping stage (it greps the TeamCity messages this prints).
     * Generated by the compiler backend as `startUnitTests`, so it cannot be renamed at the source level; it is
     * lowercased in the module bytes instead ([UNIT_TESTS_ENTRY_POINT_CORE] and this name have the same length).
     */
    const val UNIT_TESTS_ENTRY_POINT: String = "startunittests"
    private const val UNIT_TESTS_ENTRY_POINT_CORE: String = "startUnitTests"

    private const val WIT_PACKAGE = "kotlin-stdlib:wasip2"
    private const val WORLD_BOX = "wasip2-box-test"
    private const val WORLD_BOX_AND_UNIT_TESTS = "wasip2-box-test-with-unit-tests"
    private const val WORLD_UNIT_TESTS = "wasip2-unit-tests"

    private const val ADAPTER_VERSION = "47.0.3"

    private val wasmTools: String = System.getProperty("wasm.tools.path") ?: "wasm-tools"

    private val hackDir: File by lazy {
        val fromProperty = System.getProperty("kotlin.wasm.test.root.out.dir")?.let(::File)
        val dir = File(fromProperty ?: File("build"), "wasip2-component-hack")
        dir.mkdirs()
        dir
    }

    /**
     * The stdlib WIT, plus the worlds exporting the test entry points, prepared once per JVM.
     *
     * Tests run in several forked JVMs in parallel (`kotlin.test.junit5.maxParallelForks`), so this must not be a
     * shared path: preparing it means wiping and re-copying a directory, which another worker could be reading from.
     */
    private val witDir: File by lazy {
        val stdlibWit = System.getProperty("kotlin.wasm.wit.dir")?.let(::File) ?: findStdlibWitDir()
        check(stdlibWit.isDirectory) { "stdlib WIT directory not found at ${stdlibWit.absolutePath}" }

        val target = Files.createTempDirectory(hackDir.toPath(), "wit-").toFile()
        stdlibWit.copyRecursively(target, overwrite = true)
        Runtime.getRuntime().addShutdownHook(Thread { target.deleteRecursively() })
        // A world has to match the module's exports exactly, and which entry points a box test binary has depends on
        // the test (DCE drops the unit test runner from plain box tests), hence one world per combination.
        fun world(name: String, vararg exports: String) =
            """
            world $name {
                include wasi:io/imports@0.2.12;
                include wasi:random/imports@0.2.12;
                include wasi:clocks/imports@0.2.12;
                include wasi:cli/imports@0.2.12;

            ${exports.joinToString("\n") { "    export $it: func();" }}
            }
            """.trimIndent()

        File(target, "zz-box-test-world-hack.wit").writeText(
            """
            package kotlin-stdlib:wasip2@2.5.0;

            // HACK (KT-87723): `wasip2`, but exporting the box test entry points instead of `wasi:cli/run`,
            // since box test binaries have no `main`.
            ${world(WORLD_BOX, BOX_ENTRY_POINT)}

            ${world(WORLD_BOX_AND_UNIT_TESTS, BOX_ENTRY_POINT, UNIT_TESTS_ENTRY_POINT)}

            ${world(WORLD_UNIT_TESTS, UNIT_TESTS_ENTRY_POINT)}
            """.trimIndent()
        )
        target
    }

    private val adapter: File by lazy {
        System.getProperty("kotlin.wasm.wasi.adapter")?.let(::File)?.also {
            check(it.isFile) { "preview1 adapter not found at ${it.absolutePath}" }
        } ?: File(hackDir, "wasi_snapshot_preview1.reactor.wasm").also { cached ->
            if (!cached.isFile) {
                val url = "https://github.com/bytecodealliance/wasmtime/releases/download/" +
                        "v$ADAPTER_VERSION/wasi_snapshot_preview1.reactor.wasm"
                // downloaded to a private file and then moved into place, since parallel test JVMs race here as well
                val downloading = File.createTempFile("adapter-", ".wasm", hackDir)
                URI(url).toURL().openStream().use { input ->
                    downloading.outputStream().buffered().use { output -> input.copyTo(output) }
                }
                if (!downloading.renameTo(cached)) downloading.delete()
                check(cached.isFile) { "could not download the preview1 adapter from $url" }
            }
        }
    }

    private fun findStdlibWitDir(): File {
        val relative = "libraries/stdlib/wasm/wasi/internal/wit"
        var candidate: File? = File("").absoluteFile
        while (candidate != null) {
            val wit = File(candidate, relative)
            if (wit.isDirectory) return wit
            candidate = candidate.parentFile
        }
        error("Could not find '$relative' in any parent of ${File("").absolutePath}; set -Dkotlin.wasm.wit.dir=...")
    }

    /**
     * Converts [coreModule] into a component, next to the original file, and returns it.
     * Already-converted files are returned unchanged, so this is idempotent.
     */
    fun componentize(coreModule: File): File {
        check(coreModule.isFile) { "${coreModule.absolutePath} does not exist" }
        val header = coreModule.readBytes()
        // core module header: 00 61 73 6d 01 00 00 00, component header: 00 61 73 6d 0d 00 01 00
        val isCoreModule = header.size >= 8 && header[4] == 0x01.toByte() && header[6] == 0x00.toByte()
        if (!isCoreModule) return coreModule

        // the compiler-generated unit test runner export is camelCase, which WIT does not allow; both names have the
        // same length, so this is a plain byte patch (it also renames the name section entry, which is harmless)
        val renamedUnitTestsEntryPoints = header.patchAscii(UNIT_TESTS_ENTRY_POINT_CORE, UNIT_TESTS_ENTRY_POINT)
        val renamed = File(coreModule.parentFile, "${coreModule.nameWithoutExtension}.renamed.wasm")
        renamed.writeBytes(header)

        val hasUnitTestsEntryPoint = renamedUnitTestsEntryPoints > 0
        val hasBoxEntryPoint = header.containsAscii(BOX_ENTRY_POINT)
        val world = when {
            hasBoxEntryPoint && hasUnitTestsEntryPoint -> WORLD_BOX_AND_UNIT_TESTS
            hasUnitTestsEntryPoint -> WORLD_UNIT_TESTS
            else -> WORLD_BOX
        }

        val embedded = File(coreModule.parentFile, "${coreModule.nameWithoutExtension}.embedded.wasm")
        val component = File(coreModule.parentFile, "${coreModule.nameWithoutExtension}.component.wasm")
        runWasmTools(
            "component", "embed", witDir.absolutePath, renamed.absolutePath,
            "--world", "$WIT_PACKAGE/$world", "-o", embedded.absolutePath,
        )
        // WASI 0.2 native modules need no adapter at all; it is only used if something still imports preview1
        val preview1Adapter = if (header.containsAscii("wasi_snapshot_preview1")) {
            arrayOf("--adapt", "wasi_snapshot_preview1=${adapter.absolutePath}")
        } else {
            emptyArray()
        }
        runWasmTools(
            "component", "new", embedded.absolutePath, *preview1Adapter, "-o", component.absolutePath,
        )
        return component
    }

    /** Replaces all occurrences of [from] (in place, hence the same-length requirement) and returns their count. */
    private fun ByteArray.patchAscii(from: String, to: String): Int {
        require(from.length == to.length)
        val fromBytes = from.toByteArray(Charsets.US_ASCII)
        val toBytes = to.toByteArray(Charsets.US_ASCII)
        var patched = 0
        var i = 0
        outer@ while (i <= size - fromBytes.size) {
            for (j in fromBytes.indices) {
                if (this[i + j] != fromBytes[j]) {
                    i++
                    continue@outer
                }
            }
            toBytes.copyInto(this, i)
            patched++
            i += fromBytes.size
        }
        return patched
    }

    private fun ByteArray.containsAscii(value: String): Boolean {
        val valueBytes = value.toByteArray(Charsets.US_ASCII)
        var i = 0
        outer@ while (i <= size - valueBytes.size) {
            for (j in valueBytes.indices) {
                if (this[i + j] != valueBytes[j]) {
                    i++
                    continue@outer
                }
            }
            return true
        }
        return false
    }

    private fun runWasmTools(vararg arguments: String) {
        val command = listOf(wasmTools) + arguments
        val process = ProcessBuilder(command).redirectErrorStream(true).start()
        val output = process.inputStream.bufferedReader().readText()
        val exitCode = process.waitFor()
        check(exitCode == 0) {
            "Command \"${command.joinToString(" ") { escapeShellArgument(it) }}\" " +
                    "terminated with exit code $exitCode\nOUTPUT:\n$output\n---"
        }
    }
}
