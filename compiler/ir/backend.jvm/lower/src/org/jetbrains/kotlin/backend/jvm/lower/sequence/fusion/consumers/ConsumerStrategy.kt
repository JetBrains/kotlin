private val consumerFqNames = setOf(
    FOR_EACH, FOR_EACH_INDEXED, FIND, FIND_LAST, FIRST, FIRST_NOT_NULL_OF, FIRST_NOT_NULL_OF_OR_NULL, FIRST_OR_NULL, LAST, LAST_OR_NULL,
