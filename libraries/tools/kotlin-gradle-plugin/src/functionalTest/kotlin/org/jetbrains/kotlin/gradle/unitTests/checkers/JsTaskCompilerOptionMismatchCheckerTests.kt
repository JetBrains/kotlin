    @Test
    fun `module kind set on the link tasks differently from the compilation - emits diagnostic`() {
        val project = buildJsProject {
            configureLinkTasks { it.compilerOptions.moduleKind.set(JsModuleKind.MODULE_ES) }
        }
        // The TypeScript declarations generation and webpack tasks follow the link tasks, so only the link tasks are reported
        assertEquals(
            """
            |[JsTaskCompilerOptionMismatch | WARNING] JS module kind or target of tasks not aligned with their compilation
            |Compilation jsMain uses `moduleKind=umd`, but tasks `[:compileDevelopmentExecutableKotlinJs, :compileProductionExecutableKotlinJs]` use `moduleKind=es`.
            |Compilation jsTest uses `moduleKind=umd`, but tasks `[:compileTestDevelopmentExecutableKotlinJs, :compileTestProductionExecutableKotlinJs]` use `moduleKind=es`.
            |The `main` and `types` entries of 'package.json' must point to the files generated by the tasks above, but they do not, because the module kind and target of these tasks are not aligned with the compilation.
            |Set `moduleKind` and `target` only in the `kotlin { js { compilerOptions { ... } } }` block, or set the same values on the tasks as on their compilation.
            """.trimMargin(),
            project.singleMismatchDiagnostic().toString(),
        )
    }

