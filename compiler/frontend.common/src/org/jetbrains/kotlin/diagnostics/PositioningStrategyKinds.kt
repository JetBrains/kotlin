package org.jetbrains.kotlin.diagnostics

/**
 * Kinds of the standard parse-tree agnostic positioning strategies of diagnostics with source elements.
 * Their implementations for the concrete parse trees are provided by [org.jetbrains.kotlin.syntax.ParseTreeKind.positioningStrategy].
 *
 * It's an abstract class rather than an enum, so that plugins can extend it with their own strategies in the future.
 */
@Suppress("ClassName") // Suppress "Class name should not contain underscores"
abstract class PositioningStrategyKinds {
    object DEFAULT : PositioningStrategyKind()
    object SYNTAX_ERROR : PositioningStrategyKind()
    object VAL_OR_VAR_NODE : PositioningStrategyKind()
    object FUN_INTERFACE : PositioningStrategyKind()
    object COMPANION_OBJECT : PositioningStrategyKind()
    object SECONDARY_CONSTRUCTOR_DELEGATION_CALL : PositioningStrategyKind()
    object DECLARATION_RETURN_TYPE : PositioningStrategyKind()
    object CONTEXT_KEYWORD : PositioningStrategyKind()
    object DECLARATION_NAME : PositioningStrategyKind()
    object DECLARATION_NAME_ONLY : PositioningStrategyKind()
    object DECLARATION_SIGNATURE : PositioningStrategyKind()
    object CALLABLE_DECLARATION_SIGNATURE_NO_MODIFIERS : PositioningStrategyKind()
    object DECLARATION_SIGNATURE_OR_DEFAULT : PositioningStrategyKind()
    object VISIBILITY_MODIFIER : PositioningStrategyKind()
    object MODALITY_MODIFIER : PositioningStrategyKind()
    object ABSTRACT_MODIFIER : PositioningStrategyKind()
    object OPEN_MODIFIER : PositioningStrategyKind()
    object OVERRIDE_MODIFIER : PositioningStrategyKind()
    object PRIVATE_MODIFIER : PositioningStrategyKind()
    object LATEINIT_MODIFIER : PositioningStrategyKind()
    object VARIANCE_MODIFIER : PositioningStrategyKind()
    object CONST_MODIFIER : PositioningStrategyKind()
    object INLINE_OR_VALUE_MODIFIER : PositioningStrategyKind()
    object VALUE_MODIFIER : PositioningStrategyKind()
    object INNER_MODIFIER : PositioningStrategyKind()
    object FUN_MODIFIER : PositioningStrategyKind()
    object SUSPEND_MODIFIER : PositioningStrategyKind()
    object DATA_MODIFIER : PositioningStrategyKind()
    object EXPECT_ACTUAL_MODIFIER : PositioningStrategyKind()
    object OBJECT_KEYWORD : PositioningStrategyKind()
    object OPERATOR : PositioningStrategyKind()
    object REFERENCE_OR_OPERATOR : PositioningStrategyKind()
    object PARAMETER_DEFAULT_VALUE : PositioningStrategyKind()
    object PARAMETERS_WITH_DEFAULT_VALUE : PositioningStrategyKind()
    object PARAMETER_VARARG_MODIFIER : PositioningStrategyKind()
    object NAME_OF_NAMED_ARGUMENT : PositioningStrategyKind()
    object VALUE_ARGUMENTS_LIST : PositioningStrategyKind()
    object SUPERTYPES_LIST : PositioningStrategyKind()
    object DOT_BY_QUALIFIED : PositioningStrategyKind()
    object SELECTOR_BY_QUALIFIED : PositioningStrategyKind()
    object REFERENCE_BY_QUALIFIED : PositioningStrategyKind()
    object REFERENCED_NAME_BY_QUALIFIED : PositioningStrategyKind()

    /**
     * NB! The whole receiver including parentheses is marked, which is not true if we use the FIR source of the receiver
     * element with [DEFAULT] positioning.
     */
    object RECEIVER_OF_DOT_QUALIFIED : PositioningStrategyKind()
    object DEPRECATION : PositioningStrategyKind()
    object WHEN_EXPRESSION : PositioningStrategyKind()
    object WHEN_GUARD : PositioningStrategyKind()
    object IF_EXPRESSION : PositioningStrategyKind()
    object TRY_KEYWORD : PositioningStrategyKind()
    object ELSE_ENTRY : PositioningStrategyKind()
    object ARRAY_ACCESS : PositioningStrategyKind()
    object SAFE_ACCESS : PositioningStrategyKind()
    object AS_TYPE : PositioningStrategyKind()
    object USELESS_ELVIS : PositioningStrategyKind()
    object USELESS_ELVIS_LEFT : PositioningStrategyKind()
    object RETURN_WITH_LABEL : PositioningStrategyKind()
    object VARIABLE_INITIALIZER : PositioningStrategyKind()
    object WHOLE_ELEMENT : PositioningStrategyKind()
    object LONG_LITERAL_SUFFIX : PositioningStrategyKind()
    object REIFIED_MODIFIER : PositioningStrategyKind()
    object TYPE_PARAMETERS_LIST : PositioningStrategyKind()
    object FUNCTION_TYPE_RECEIVER : PositioningStrategyKind()
    object NAME_IDENTIFIER : PositioningStrategyKind()
    object REDUNDANT_NULLABLE : PositioningStrategyKind()
    object QUESTION_MARK_BY_TYPE : PositioningStrategyKind()
    object ANNOTATION_USE_SITE : PositioningStrategyKind()
    object IMPORT_LAST_NAME : PositioningStrategyKind()
    object IMPORT_LAST_BUT_ONE_NAME : PositioningStrategyKind()
    object SPREAD_OPERATOR : PositioningStrategyKind()
    object DECLARATION_WITH_BODY : PositioningStrategyKind()
    object COMMAS : PositioningStrategyKind()
    object UNREACHABLE_CODE : PositioningStrategyKind()
    object ACTUAL_DECLARATION_NAME : PositioningStrategyKind()
    object LABEL : PositioningStrategyKind()
    object NOT_SUPPORTED_IN_INLINE_MOST_RELEVANT : PositioningStrategyKind()
    object INLINE_PARAMETER_MODIFIER : PositioningStrategyKind()
    object INLINE_FUN_MODIFIER : PositioningStrategyKind()
    object OPERATOR_MODIFIER : PositioningStrategyKind()
    object INFIX_MODIFIER : PositioningStrategyKind()
    object NON_FINAL_MODIFIER_OR_NAME : PositioningStrategyKind()
    object ENUM_MODIFIER : PositioningStrategyKind()
    object FIELD_KEYWORD : PositioningStrategyKind()
    object TAILREC_MODIFIER : PositioningStrategyKind()
    object EXTERNAL_MODIFIER : PositioningStrategyKind()
    object PROPERTY_DELEGATE : PositioningStrategyKind()
    object IMPORT_ALIAS : PositioningStrategyKind()
    object DECLARATION_START_TO_NAME : PositioningStrategyKind()
    object DELEGATED_SUPERTYPE_BY_KEYWORD : PositioningStrategyKind()
    object PROPERTY_DELEGATE_BY_KEYWORD : PositioningStrategyKind()
    object CALL_ELEMENT_WITH_DOT : PositioningStrategyKind()
    object TYPEALIAS_TYPE_REFERENCE : PositioningStrategyKind()
    object SUPERTYPE_INITIALIZED_IN_EXPECTED_CLASS_DIAGNOSTIC : PositioningStrategyKind()
    object TYPE_ARGUMENT_LIST_OR_SELF : PositioningStrategyKind()
    object TYPE_ARGUMENT_LIST_OR_WITHOUT_RECEIVER : PositioningStrategyKind()
    object PACKAGE_DIRECTIVE_NAME_EXPRESSION : PositioningStrategyKind()
    object OUTERMOST_PARENTHESES_IN_ASSIGNMENT_LHS : PositioningStrategyKind()
    object DESTRUCTURING_DECLARATION_ENTRIES : PositioningStrategyKind()
}
