     * element with [DEFAULT] positioning.
     */
    object RECEIVER_OF_DOT_QUALIFIED : SourceElementPositioningStrategy()
    object DEPRECATION : SourceElementPositioningStrategy()
    object WHEN_EXPRESSION : SourceElementPositioningStrategy()
    object WHEN_GUARD : SourceElementPositioningStrategy()
    object IF_EXPRESSION : SourceElementPositioningStrategy()
    object TRY_KEYWORD : SourceElementPositioningStrategy()
    object ELSE_ENTRY : SourceElementPositioningStrategy()
    object ARRAY_ACCESS : SourceElementPositioningStrategy()
    object SAFE_ACCESS : SourceElementPositioningStrategy()
    object AS_TYPE : SourceElementPositioningStrategy()
    object USELESS_ELVIS : SourceElementPositioningStrategy()
