/**
 * Links the references of a deserialized inline function body to the declarations of the compilation that is running.
 *
 * [org.jetbrains.kotlin.backend.common.serialization.NonLinkingIrInlineFunctionDeserializer] reads the inline function bodies of
 * the dependencies into a symbol table of its own and deliberately leaves the symbols they refer to unbound: the other KLIB-based
 * backends serialize those bodies straight back into a KLIB, and it is the consumer of that KLIB that links them.
 *
 * The consumer of the JKlib IR takes the IR directly, so the references have to be resolved here. This is possible because the
 * full transitive closure of the dependencies is passed to the compiler, so every referenced declaration that is part of the KLIB
 * metadata is reachable through the `SymbolFinder`. The declarations that exist only in the IR of the KLIB, such as the synthetic
 * accessors generated by the first phase, are deserialized by [JKlibIrOnlyDeclarationDeserializer].
 *
 * Resolution is exact: a candidate is accepted only when the signature computed from it equals the requested one. When nothing
 * matches, `null` is returned and the reference is left unbound, which is the default behavior.
 */
internal class JKlibInlineFunctionSymbolResolver(context: JKlibPreSerializationLoweringContext) {
    private val irBuiltIns = context.irBuiltIns
    private val symbolFinder = irBuiltIns.symbolFinder
    private val signatureComputer = PublicIdSignatureComputer(context.irMangler)
    private val cache = HashMap<IdSignature, IrSymbol?>()
    private val irOnlyDeclarationDeserializer = JKlibIrOnlyDeclarationDeserializer(irBuiltIns, context.resolvedLibraries, ::resolve)

    /**
     * The IR intrinsics, such as `EQEQ`. They are synthesized by `IrBuiltIns` and have no FIR counterpart, so the `SymbolFinder`
     * can't see them, but the inline function bodies of the dependencies do refer to them.
     */
    private val builtInFunctions: List<IrSimpleFunction> by lazy {
        irBuiltIns.operatorsPackageFragment.declarations.filterIsInstance<IrSimpleFunction>()
    }

    fun resolve(signature: IdSignature, symbolKind: BinarySymbolData.SymbolKind): IrSymbol? {
        val cached = cache[signature]
        if (cached != null || cache.containsKey(signature)) return cached
        return resolveUncached(signature, symbolKind).also { cache[signature] = it }
    }

    private fun resolveUncached(signature: IdSignature, symbolKind: BinarySymbolData.SymbolKind): IrSymbol? =
        when (symbolKind) {
            BinarySymbolData.SymbolKind.CLASS_SYMBOL -> findClass(signature)
            BinarySymbolData.SymbolKind.CONSTRUCTOR_SYMBOL -> findConstructor(signature)
            BinarySymbolData.SymbolKind.ENUM_ENTRY_SYMBOL -> findEnumEntry(signature)
            BinarySymbolData.SymbolKind.FUNCTION_SYMBOL -> findFunction(signature)
            BinarySymbolData.SymbolKind.PROPERTY_SYMBOL -> findProperty(signature)
            BinarySymbolData.SymbolKind.FIELD_SYMBOL,
            BinarySymbolData.SymbolKind.STANDALONE_FIELD_SYMBOL -> findField(signature)
            else -> null
        }

    /** A class is uniquely identified by its [ClassId], so no signature check is needed. */
    private fun findClass(signature: IdSignature): IrClassSymbol? {
        val common = signature.asPublic() ?: return null
        return symbolFinder.findClass(ClassId(FqName(common.packageFqName), FqName(common.declarationFqName), isLocal = false))
    }

    private fun findFunction(signature: IdSignature): IrSymbol? {
        if (signature is IdSignature.AccessorSignature) {
            val property = findProperty(signature.propertySignature)?.owner ?: return null
            return listOfNotNull(property.getter, property.setter).matching(signature)?.symbol
        }
        val common = signature.asPublic() ?: return null
        val enclosingClass = enclosingClassOf(common)
        val candidates = enclosingClass?.members<IrSimpleFunction>(common.shortName)
            ?: (symbolFinder.findFunctions(common.callableId()).map { it.owner } + builtInFunctions)
        return candidates.matching(signature)?.symbol
        // The declarations generated by the first phase, such as synthetic accessors, are not in the metadata the lazy
        // declarations are built from, but only in the IR of the KLIB.
            ?: deserializeIrOnlyFunction(enclosingClass, signature)?.symbol
    }

    private fun deserializeIrOnlyFunction(enclosingClass: IrClassSymbol?, signature: IdSignature): IrSimpleFunction? {
        val declaration = if (enclosingClass != null) {
            irOnlyDeclarationDeserializer.deserializeMember(enclosingClass.owner, signature)
        } else {
            irOnlyDeclarationDeserializer.deserializeTopLevel(signature)
        }
        return declaration as? IrSimpleFunction
    }

    private fun findProperty(signature: IdSignature): IrPropertySymbol? {
        val common = signature.asPublic() ?: return null
        val candidates = enclosingClassOf(common)?.members<IrProperty>(common.shortName)
            ?: symbolFinder.findProperties(common.callableId()).map { it.owner }
        return candidates.matching(signature)?.symbol
    }

    private fun findConstructor(signature: IdSignature): IrSymbol? {
        val common = signature.asPublic() ?: return null
        return enclosingClassOf(common)?.members<IrConstructor>(common.shortName)?.matching(signature)?.symbol
    }

    private fun findEnumEntry(signature: IdSignature): IrSymbol? {
        val common = signature.asPublic() ?: return null
        return enclosingClassOf(common)
            ?.members<IrEnumEntry>(common.shortName)
            ?.matching(signature)
            ?.symbol
    }

    /**
     * A backing field is signed as the signature of its property with the `<BF>` marker appended, see `IdSignatureBuilder`. A
     * field with no property of its own keeps a signature of its own.
     */
    private fun findField(signature: IdSignature): IrSymbol? {
        val propertySignature = signature.backingFieldOwnerOrNull()
        if (propertySignature != null) {
            return findProperty(propertySignature)?.owner?.backingField?.symbol
        }
        val common = signature.asPublic() ?: return null
        return enclosingClassOf(common)
            ?.members<IrField>(common.shortName)
            ?.matching(signature)
            ?.symbol
    }

    private fun IdSignature.backingFieldOwnerOrNull(): IdSignature? =
        (this as? IdSignature.CompositeSignature)
            ?.takeIf { (it.inner as? IdSignature.LocalSignature)?.localFqn == MangleConstant.BACKING_FIELD_NAME }
            ?.container

    /**
     * The class a member declaration belongs to, or `null` when the declaration is top level. The last name segment of a member
     * signature is always the name of the member itself, so everything before it is the class it is nested in.
     */
    private fun enclosingClassOf(common: IdSignature.CommonSignature): IrClassSymbol? {
        val classSegments = common.nameSegments.dropLast(1)
        if (classSegments.isEmpty()) return null
        return symbolFinder.findClass(ClassId(FqName(common.packageFqName), FqName.fromSegments(classSegments), isLocal = false))
    }

    private inline fun <reified T : IrDeclarationWithName> IrClassSymbol.members(name: String): List<T> =
        owner.declarations.filterIsInstance<T>().filter { it.name.asString() == name }

    private fun <T : IrDeclaration> List<T>.matching(signature: IdSignature): T? =
        firstOrNull { signatureComputer.computeSignature(it) == signature }

    private fun IdSignature.CommonSignature.callableId() =
        CallableId(FqName(packageFqName), Name.guessByFirstCharacter(shortName))
}
