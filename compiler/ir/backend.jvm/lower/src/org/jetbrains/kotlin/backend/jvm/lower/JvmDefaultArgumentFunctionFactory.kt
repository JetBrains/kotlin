package org.jetbrains.kotlin.backend.jvm.lower

import org.jetbrains.kotlin.backend.common.CommonBackendContext
import org.jetbrains.kotlin.backend.common.lower.*
import org.jetbrains.kotlin.backend.jvm.InlineClassAbi
import org.jetbrains.kotlin.backend.jvm.withoutJvmExposeBoxedAnnotation
import org.jetbrains.kotlin.ir.expressions.IrAnnotation
import org.jetbrains.kotlin.ir.types.IrType

internal class JvmDefaultArgumentFunctionFactory(context: CommonBackendContext) : MaskedDefaultArgumentFunctionFactory(context) {
    override fun IrType.hasNullAsUndefinedValue() =
        (InlineClassAbi.unboxType(this) ?: this) !in context.irBuiltIns.primitiveIrTypes

    // Never expose default stubs.
    //
    // Exposed copy generated by JvmInlineClassLowering never keeps default values, so there is no boxed $default to link against.
    // A callee from another module is still annotated with @JvmExposeBoxed -
    // JvmInlineClassLowering only strips it from declarations of the module being compiled,
    // thus MethodSignatureMapper would then box its inline class parameters, producing a reference to a method which does not exist.
    //
    // See KT-88324.
    override fun filterCopiedAnnotations(annotations: List<IrAnnotation>): List<IrAnnotation> =
        annotations.withoutJvmExposeBoxedAnnotation()
}
