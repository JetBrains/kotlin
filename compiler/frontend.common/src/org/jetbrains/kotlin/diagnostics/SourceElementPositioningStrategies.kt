    object DEFAULT : SourceElementPositioningStrategy()
    object SYNTAX_ERROR : SourceElementPositioningStrategy()
    object VAL_OR_VAR_NODE : SourceElementPositioningStrategy()
    object FUN_INTERFACE : SourceElementPositioningStrategy()
    object COMPANION_OBJECT : SourceElementPositioningStrategy()
    object SECONDARY_CONSTRUCTOR_DELEGATION_CALL : SourceElementPositioningStrategy()
    object DECLARATION_RETURN_TYPE : SourceElementPositioningStrategy()
    object CONTEXT_KEYWORD : SourceElementPositioningStrategy()
    object DECLARATION_NAME : SourceElementPositioningStrategy()
    object DECLARATION_NAME_ONLY : SourceElementPositioningStrategy()
    object DECLARATION_SIGNATURE : SourceElementPositioningStrategy()
    object CALLABLE_DECLARATION_SIGNATURE_NO_MODIFIERS : SourceElementPositioningStrategy()
    object DECLARATION_SIGNATURE_OR_DEFAULT : SourceElementPositioningStrategy()
    object VISIBILITY_MODIFIER : SourceElementPositioningStrategy()
    object MODALITY_MODIFIER : SourceElementPositioningStrategy()
    object ABSTRACT_MODIFIER : SourceElementPositioningStrategy()
    object OPEN_MODIFIER : SourceElementPositioningStrategy()
    object OVERRIDE_MODIFIER : SourceElementPositioningStrategy()
    object PRIVATE_MODIFIER : SourceElementPositioningStrategy()
    object LATEINIT_MODIFIER : SourceElementPositioningStrategy()
    object VARIANCE_MODIFIER : SourceElementPositioningStrategy()
    object CONST_MODIFIER : SourceElementPositioningStrategy()
    object INLINE_OR_VALUE_MODIFIER : SourceElementPositioningStrategy()
    object VALUE_MODIFIER : SourceElementPositioningStrategy()
    object INNER_MODIFIER : SourceElementPositioningStrategy()
    object FUN_MODIFIER : SourceElementPositioningStrategy()
    object SUSPEND_MODIFIER : SourceElementPositioningStrategy()
    object DATA_MODIFIER : SourceElementPositioningStrategy()
    object EXPECT_ACTUAL_MODIFIER : SourceElementPositioningStrategy()
    object OBJECT_KEYWORD : SourceElementPositioningStrategy()
    object OPERATOR : SourceElementPositioningStrategy()
    object REFERENCE_OR_OPERATOR : SourceElementPositioningStrategy()
    object PARAMETER_DEFAULT_VALUE : SourceElementPositioningStrategy()
    object PARAMETERS_WITH_DEFAULT_VALUE : SourceElementPositioningStrategy()
    object PARAMETER_VARARG_MODIFIER : SourceElementPositioningStrategy()
    object NAME_OF_NAMED_ARGUMENT : SourceElementPositioningStrategy()
    object VALUE_ARGUMENTS_LIST : SourceElementPositioningStrategy()
    object SUPERTYPES_LIST : SourceElementPositioningStrategy()
    object DOT_BY_QUALIFIED : SourceElementPositioningStrategy()
