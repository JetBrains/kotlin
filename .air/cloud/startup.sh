#!/usr/bin/env bash
# Air cloud environment startup script for the Kotlin repository.
# AIR_STARTUP_MODE=warmup: prime Gradle/JDK/dependency caches and verify the build (snapshot-baking run).
# AIR_STARTUP_MODE=task:   only lightweight per-launch configuration; exits promptly.
set -euo pipefail

if [ "${AIR_STARTUP_MODE:-}" = warmup ]; then WARMUP=1; else WARMUP=; fi

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_DIR"

log() { echo "[startup $(date +%H:%M:%S)] $*"; }

# --- Gradle proxy configuration -------------------------------------------------------------
# The JVM ignores HTTPS_PROXY, so Gradle (wrapper download, dependency resolution, toolchain
# provisioning) needs explicit proxy system properties in the user-level gradle.properties.
configure_gradle_proxy() {
  local props="$HOME/.gradle/gradle.properties" begin="# >>> air proxy >>>" end="# <<< air proxy <<<"
  mkdir -p "$HOME/.gradle"
  touch "$props"
  sed -i "/^$begin\$/,/^$end\$/d" "$props"
  local proxy="${HTTPS_PROXY:-${https_proxy:-}}"
  if [ -z "$proxy" ]; then
    log "no HTTPS_PROXY set; skipping Gradle proxy configuration"
    return
  fi
  local hostport="${proxy#*://}"
  hostport="${hostport#*@}"
  hostport="${hostport%%/*}"
  local host="${hostport%:*}" port="${hostport##*:}"
  {
    echo "$begin"
    for scheme in http https; do
      echo "systemProp.$scheme.proxyHost=$host"
      echo "systemProp.$scheme.proxyPort=$port"
    done
    echo "systemProp.http.nonProxyHosts=localhost|127.0.0.1|::1"
    echo "$end"
  } >> "$props"
  log "configured Gradle proxy $host:$port in $props"
}

# --- JDKs ----------------------------------------------------------------------------------
# The build needs JDK 8, 11, 17, 21 and 25 toolchains (see org.gradle.java.installations.fromEnv in
# gradle.properties); Gradle's auto-provisioning is not configured for every included build, so
# install Temurin JDKs ourselves and register them via JDK_* variables and installations.paths.
JDKS_DIR="$HOME/.jdks"
declare -A JDK_VARS=([8]=JDK_1_8 [11]=JDK_11_0 [17]=JDK_17_0 [21]=JDK_21_0 [25]=JDK_25_0)

install_jdks() {
  local v dir
  mkdir -p "$JDKS_DIR"
  for v in 8 11 17 21 25; do
    dir="$JDKS_DIR/temurin-$v"
    if [ -x "$dir/bin/java" ]; then continue; fi
    log "installing Temurin JDK $v into $dir"
    rm -rf "$dir.tmp" && mkdir -p "$dir.tmp"
    curl -fsSL --retry 3 "https://api.adoptium.net/v3/binary/latest/$v/ga/linux/x64/jdk/hotspot/normal/eclipse" \
      | tar -xz -C "$dir.tmp" --strip-components=1
    mv "$dir.tmp" "$dir"
    log "installed JDK $v: $("$dir/bin/java" -version 2>&1 | head -1)"
  done
}

write_env_file() {
  local env_file="$HOME/.air-kotlin-env.sh" marker="# air-kotlin-env" profile f v
  {
    echo "# Generated by .air/cloud/startup.sh: JDK toolchains for the Kotlin build"
    for v in 8 11 17 21 25; do echo "export ${JDK_VARS[$v]}=\"$JDKS_DIR/temurin-$v\""; done
  } > "$env_file"
  profile=""
  for f in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
    if [ -f "$f" ]; then profile="$f"; break; fi
  done
  [ -n "$profile" ] || profile="$HOME/.profile"
  for f in "$profile" "$HOME/.bashrc"; do
    touch "$f"
    grep -qF "$marker" "$f" || echo "[ -f \"$env_file\" ] && . \"$env_file\" $marker" >> "$f"
  done
  # shellcheck disable=SC1090
  . "$env_file"
}

register_jdks_with_gradle() {
  local props="$HOME/.gradle/gradle.properties" paths="" v
  for v in 8 11 17 21 25; do paths="$paths${paths:+,}$JDKS_DIR/temurin-$v"; done
  sed -i '/^org.gradle.java.installations.paths=/d' "$props"
  echo "org.gradle.java.installations.paths=$paths" >> "$props"
}

configure_gradle_proxy
install_jdks
write_env_file
register_jdks_with_gradle
chmod +x gradlew

# Builds the compiler distribution (dist/kotlinc) and checks it can compile and run a program.
# In warmup this also fills the Gradle wrapper, dependency and build caches for the snapshot.
healthcheck() {
  log "healthcheck: ./gradlew dist (cold run takes a while)"
  ./gradlew dist --console=plain
  log "healthcheck: compiling a smoke program with dist/kotlinc"
  local tmp
  tmp="$(mktemp -d)"
  echo 'fun main() { println("kotlin-smoke-ok") }' > "$tmp/smoke.kt"
  dist/kotlinc/bin/kotlinc "$tmp/smoke.kt" -include-runtime -d "$tmp/smoke.jar"
  "$JDK_21_0/bin/java" -jar "$tmp/smoke.jar" | grep -q kotlin-smoke-ok
  rm -rf "$tmp"
  log "healthcheck: OK"
}

if [ -n "$WARMUP" ]; then
  healthcheck
fi
log "startup finished (mode=${AIR_STARTUP_MODE:-unset})"
